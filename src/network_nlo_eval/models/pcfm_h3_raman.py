def _active_pumps(pumps: Sequence[RamanPumpConfig] | None) -> list[RamanPumpConfig]:
    """Return the pumps that carry positive power.

    Args:
        pumps: Pump list, possibly ``None`` or containing zero-power entries.

    Returns
    -------
        A new list with only the pumps of positive power.
    """
    if not pumps:
        return []
    return [pump for pump in pumps if float(pump.power_w) > 0.0]


def _resolve_egn(egn: bool | str, pumps: Sequence[RamanPumpConfig] | None) -> bool:
    """Resolve the EGN switch of the model.

    ``"auto"`` turns the correction off as soon as one active pump is forward:
    the Zefreh 2020 fit does not cover forward-pumped Raman links, and the
    forward audit shows it makes H3 optimistic by 0.4–0.7 dB.  No pump and
    backward-only pump sets keep it on, so they stay bit-for-bit unchanged.
    Explicit ``True``/``False`` are passed through.

    Args:
        egn: ``"auto"``, ``True`` or ``False``.
        pumps: Pumps that drive the link; only positive-power pumps count.

    Returns
    -------
        ``True`` when the correction is applied.

    Raises
    ------
        ValueError: ``egn`` is neither a bool nor ``"auto"``.
    """
    if isinstance(egn, bool):
        return egn
    if not isinstance(egn, str) or egn != "auto":
        raise ValueError(f"egn must be True, False or 'auto', got {egn!r}.")
    return not any(pump.direction == "forward" for pump in _active_pumps(pumps))


def _resolve_nli_convention(
    nli_power_convention: str | None,
    launch_power_convention: str,
) -> str:
    """Resolve the NLI power convention of the H3 kernel.

    ``None``/``"auto"`` follows the declared launch convention: the NLI is
    then driven by the physical total power whenever the caller declared
    ``"per_pol"`` and the input really is per-polarization.  An explicit
    ``"total"`` is kept as a comparison control: it reproduces the pre-audit
    NLI (8x low under a per-polarization launch) without changing the ODE.
    The opposite explicit combination is rejected because it would drive the
    GN weights with ``2 * P`` while the caller already passed the total power.

    Args:
        nli_power_convention: ``None``, ``"auto"``, ``"total"`` or ``"per_pol"``.
        launch_power_convention: Already resolved launch convention.

    Returns
    -------
        ``"total"`` or ``"per_pol"``.

    Raises
    ------
        ValueError: The value is unknown, or it contradicts the launch
            convention.
    """
    if nli_power_convention is None or str(nli_power_convention) == "auto":
        return "per_pol" if launch_power_convention == "per_pol" else "total"
    resolved = resolve_nli_power_convention(nli_power_convention)
    if resolved == "per_pol" and launch_power_convention != "per_pol":
        raise ValueError(
            "nli_power_convention='per_pol' requires launch_power_convention='per_pol': "
            "the NLI kernels would otherwise drive the dual-polarization GN weights with "
            "2x a power that is already the per-channel total power. Pass "
            "launch_power_convention='per_pol' with power_in_w = P_total/2, or "
            "nli_power_convention='total'."
        )
    return resolved


class PCFH3RamanSpanKernel(PCFMSpanKernel):
    """PCFM kernel whose SPP is the coupled signal/pump profile of one span.

    The class inherits the SCI/XCI kernels, the edge fix, the polynomial fit and
    the span memoisation of :class:`PCFMSpanKernel`.  It overrides only the
    profile provider: with active pumps the normalised SPP comes from a coarse
    coupled-ODE solve, and the same solve supplies the Raman ASE.  With no
    active pump every call falls through to the parent, which is what makes the
    no-pump path bit-for-bit identical to H3 PCFM.

    Args:
        f_abs_hz: ``(N,)`` channel centre frequencies (Hz).
        b_hz: ``(N,)`` channel bandwidths (Hz).
        fiber_config: Fibre parameters of the span.
        pumps: Pumps applied to the span; only positive-power pumps are used.
        gain_model: Raman gain spectrum model, or ``"gaussian"``/``"linear"``
            to build one.  A table spectrum is built with
            :meth:`~network_nlo_eval.models.raman.RamanGainModel.from_table`
            and passed as an instance.
        raman_ase: Expose the newly generated Raman ASE to the route layer.
        raman_steps: RK4 steps of the coarse signal/pump/ASE solve.
        raman_iterations: Fixed-point iterations cap of the backward-pump solve.
        include_isrs: Include channel-channel ISRS in the coupled solve.
        pump_depletion: Let the pumps be depleted by the signals.  ``True``
            (default) solves the full coupled Eq. (2); ``False`` freezes the
            pump evolution to its own attenuation, the undepleted-pump control
            convention of the waveform reference.
        signal_polarizations: Polarizations represented by each ODE signal
            state.  ``1`` (default) is the historical per-polarization drive
            (bit-for-bit unchanged); ``2`` drives the coupling with the
            dual-polarization total signal power, the physical waveform
            convention.
        pump_pump_raman: Include pump-pump Raman coupling in the coupled ODE.
            ``True`` (default) keeps the historical behaviour; ``False`` zeroes
            only the pump-pump block, leaving pump depletion by the signals,
            the pump own attenuation, and the pump-signal / signal-signal
            coupling untouched.  A control convention for the C+L residual
            audit.
        launch_power_convention: Power convention of ``power_in_w``.
            ``"total"`` (default) means per-channel dual-polarization total
            power; ``"per_pol"`` means per-polarization power, so the physical
            total is ``2 * power_in_w`` and ``signal_polarizations`` must be
            ``2``.  The ODE state and the output stay per-polarization in both
            cases; only the coupling drive differs.  See
            :func:`~network_nlo_eval.models.raman_ode.resolve_launch_power_convention`.
        nli_power_convention: Power convention of the NLI kernels.  ``None``
            (default) follows ``launch_power_convention``: ``"per_pol"`` when
            the launch is per-polarization, ``"total"`` otherwise.  An explicit
            ``"total"`` under a per-polarization launch keeps the pre-audit
            NLI (8x too low) as a comparison control; ``"per_pol"`` under a
            total-power launch is rejected because it would double-count the
            power.  See :class:`~network_nlo_eval.models.pcfm.PCFMSpanKernel`.
        pump_signal_overlap_guard_hz: Guard added to each side of the channel
            band edges when the pump/signal overlap is decided (Hz).
            ``0`` (default) keeps the literal band; a positive value widens it
            for the pump linewidth / WDM transition, a negative value shrinks
            it as an explicit control.  Only the validity report changes.
        dense_grid_fix: Opt-in overlap-aware XCI correction forwarded to
            :class:`PCFMSpanKernel`.  ``False`` (default) keeps the historic
            numbers bit-for-bit.
        lumped_loss: Lumped loss elements inside the span
            (``(position_m, loss_db)``), paper Section IV-D.  Positions must
            lie strictly inside ``(0, L)``, the loss must be non-negative, and
            duplicate positions are merged by summing their dB.  ``None``
            (default) keeps every existing number bit-for-bit.  Without
            active pumps the list is forwarded unchanged to
            :class:`~network_nlo_eval.models.pcfm.PCFMSpanKernel`, which
            already applies it to the ISRS-only SPP.  With active pumps the
            coupled signal/pump/ASE ODE is integrated segment by segment and
            every state is multiplied by ``10**(-loss_db/10)`` at each loss
            position (forward states on the way out, backward pumps in the
            ``s = L - z`` coordinate at the same physical position).
        raman_resolution_check: Opt-in read-only resolution audit.  When
            ``True`` the validity report solves the same span at a finer step
            count and compares the normalised signal profile, the span-end
            gain and the newly generated Raman ASE with the solved result.
            ``False`` (default) constructs no extra solver and keeps every
            point value bit-for-bit identical.
        raman_resolution_tol: Relative tolerance (fraction) above which the
            audit sets ``raman_auto_under_resolved``.  Must be finite and
            positive; default :data:`DEFAULT_RAMAN_RESOLUTION_TOL` (10 %).
        **kwargs: Forwarded to :class:`PCFMSpanKernel`.
    """

    def __init__(
        self,
        f_abs_hz: NDArrayFloat,
        b_hz: NDArrayFloat,
        fiber_config: FiberSpanConfig,
        *,
        pumps: Sequence[RamanPumpConfig] | None = None,
        gain_model: RamanGainModel | str,
        raman_ase: bool = True,
        raman_steps: int = DEFAULT_H3_RAMAN_STEPS,
        raman_iterations: int = DEFAULT_H3_RAMAN_ITERATIONS,
        include_isrs: bool = True,
        pump_depletion: bool = True,
        signal_polarizations: int = 1,
        pump_pump_raman: bool = True,
        launch_power_convention: str = "total",
        nli_power_convention: str | None = None,
        pump_signal_overlap_guard_hz: float = PUMP_SIGNAL_OVERLAP_GUARD_HZ,
        dense_grid_fix: bool = False,
        lumped_loss: Sequence[tuple[float, float]] | None = None,
        raman_resolution_check: bool = False,
        raman_resolution_tol: float = DEFAULT_RAMAN_RESOLUTION_TOL,
        **kwargs: object,
    ) -> None:
        """Build the kernel and cache the pump-side constants.

        Raises
        ------
            ValueError: ``raman_steps`` or ``raman_iterations`` is not positive,
                or a boolean option is not a ``bool``, or the
                ``launch_power_convention``/``signal_polarizations``/``nli_power_convention``
                combination is inconsistent, or the overlap guard is not finite,
                or a lumped loss position is outside ``(0, L)`` of the fibre.
        """
        if int(raman_steps) < 4:
            raise ValueError(f"raman_steps must be >= 4, got {raman_steps}.")
        if int(raman_iterations) < 1:
            raise ValueError(f"raman_iterations must be >= 1, got {raman_iterations}.")
        if not isinstance(raman_resolution_check, (bool, np.bool_)):
            raise ValueError(f"raman_resolution_check must be a bool, got {raman_resolution_check!r}.")
        resolved_resolution_tol = float(raman_resolution_tol)
        if not np.isfinite(resolved_resolution_tol) or resolved_resolution_tol <= 0.0:
            raise ValueError(
                f"raman_resolution_tol must be a finite positive fraction, got {raman_resolution_tol!r}."
            )
        if not isinstance(pump_pump_raman, (bool, np.bool_)):
            raise ValueError(f"pump_pump_raman must be a bool, got {pump_pump_raman!r}.")
        if int(signal_polarizations) < 1:
            raise ValueError("signal_polarizations must be >= 1.")
        resolved_guard = float(pump_signal_overlap_guard_hz)
        if not np.isfinite(resolved_guard):
            raise ValueError(
                f"pump_signal_overlap_guard_hz must be finite, got {pump_signal_overlap_guard_hz!r}."
            )
        resolved_convention = resolve_launch_power_convention(launch_power_convention, signal_polarizations)
        resolved_nli = _resolve_nli_convention(nli_power_convention, resolved_convention)
        # 位置上限按光纤长度校验；实际评估的跨长在构造 solver 时还会再校验一次。
        fiber_length_m = float(fiber_config.length_km) * 1e3
        checked_lumped_loss, _, _ = _resolve_lumped_loss(lumped_loss, fiber_length_m)
        super().__init__(
            f_abs_hz,
            b_hz,
            fiber_config,
            lumped_loss=checked_lumped_loss or None,
            nli_power_convention=resolved_nli,
            dense_grid_fix=bool(dense_grid_fix),
            **kwargs,  # type: ignore[arg-type]
        )
        self._fiber_config = fiber_config
        self._raman_pumps = _active_pumps(pumps)
        # 泵频率在构造期固定，重叠判定只需要信号带边界，因此没有热路径开销。
        self._pump_frequencies_hz = np.asarray(
            [C_LIGHT / (float(pump.wavelength_nm) * 1e-9) for pump in self._raman_pumps],
            dtype=np.float64,
        )
        self._pump_signal_overlap_guard_hz = resolved_guard
        self._pump_overlap_warned = False
        self._raman_gain_model = resolve_raman_gain_model(gain_model)
        self._raman_ase = bool(raman_ase)
        self.raman_steps = int(raman_steps)
        self.raman_iterations = int(raman_iterations)
        self.raman_resolution_check = bool(raman_resolution_check)
        self.raman_resolution_tol = float(resolved_resolution_tol)
        self.include_isrs = bool(include_isrs)
        self.pump_depletion = bool(pump_depletion)
        self.signal_polarizations = int(signal_polarizations)
        self.pump_pump_raman = bool(pump_pump_raman)
        self.launch_power_convention = resolved_convention
        # 宽波段多泵/前向是粗 ODE 最难的区域：auto 在这里升到 96 步，报告里也
        # 单独标出，便于调用方区分“默认已收敛”和“收敛是靠扩展步数得到的”。
        self._wideband_multipump = (
            bool(self._raman_pumps)
            and (
                any(str(pump.direction) == "forward" for pump in self._raman_pumps)
                or len(self._raman_pumps) >= 4
            )
            and _reaches_s_band(self.f_abs_hz)
        )
        self._solver_cache: dict[int, RamanPaperSpanSolver] = {}
        self._raman_cache: list[tuple[NDArrayFloat, int, PaperRamanSpanResult]] = []
        # Opt-in resolution audit only.  Both caches stay empty with the
        # default ``raman_resolution_check=False``, so no extra solver is
        # constructed on the default path.
        self._resolution_solver_cache: dict[tuple[int, int], RamanPaperSpanSolver] = {}
        self._resolution_result_cache: list[tuple[NDArrayFloat, int, int, PaperRamanSpanResult]] = []
        # Number of coupled ODE solves actually performed by this kernel.  It
        # is a read-only performance counter: the default path only ever
        # increments it for the solved-step result.
        self.perf_ode_solves = 0
        # 泵浦自身衰减系数：耗尽度要相对“无信号时”的泵浦出射功率定义，
        # 否则把 25 dB 的本征损耗误当成耗尽。
        self._pump_alpha_npm: NDArrayFloat | None = None
        self._last_raman_ase_internal = np.zeros(self.n_nodes, dtype=np.float64)
        # Net fibre gain of the last evaluated span (model order).  It is a side
        # output for the uncertainty layer: the route EDFA compensates per
        # channel, so the path result has no gain tilt left to measure.
        self._last_span_gain = np.ones(self.n_nodes, dtype=np.float64)
        self.last_raman_iterations = 0
        self.last_raman_converged = True
        self.last_pump_power_out_w: NDArrayFloat | None = None
        # 2019b 调制格式修正：参考核（semrau2019，egn=True）与单槽比值缓存。
        # 默认 None，未开启修正时热路径完全不读它们。
        self._mf_reference: Semrau2019SpanKernel | None = None
        self._mf_ratio_cache: (
            tuple[tuple[float, int], NDArrayFloat, NDArrayFloat] | None
        ) = None

    @property
    def active(self) -> bool:
        """Whether at least one pump carries positive power."""
        return bool(self._raman_pumps)

    @property
    def active_pumps(self) -> tuple[RamanPumpConfig, ...]:
        """Active (positive-power) pumps of the span, in configuration order."""
        return tuple(self._raman_pumps)

    @property
    def pump_signal_overlap_guard_hz(self) -> float:
        """Guard added to each side of the signal band edges (Hz).

        ``0`` is the default and keeps the literal channel-edge band.  A
        positive value widens the band for the pump linewidth / WDM transition,
        a negative one shrinks it.  It only affects the validity report.
        """
        return float(self._pump_signal_overlap_guard_hz)

    @property
    def wideband_multipump(self) -> bool:
        """Whether the span is in the S/E multi-pump (extended-step) regime.

        ``raman_steps="auto"`` raises the step count to
        :data:`WIDEBAND_MULTIPUMP_RAMAN_STEPS` here.  The flag is reported
        independently of the final convergence so an explicitly under-resolved
        kernel (``raman_steps=12``) is still visible downstream.
        """
        return bool(self._wideband_multipump)

    @property
    def lumped_loss_in_ode(self) -> bool:
        """Whether the lumped loss is applied inside the coupled Raman ODE.

        ``True`` only when the span carries at least one lumped loss element
        *and* at least one active pump.  Without pumps the parent
        :class:`~network_nlo_eval.models.pcfm.PCFMSpanKernel` applies the same
        list to its ISRS-only SPP.
        """
        return bool(self.active and self.lumped_loss)

    @property
    def lumped_loss_segments(self) -> int:
        """Number of integration segments created by the lumped loss.

        ``len(self.lumped_loss) + 1``; ``1`` when no element is configured (the
        whole span is a single segment).
        """
        return len(self.lumped_loss) + 1

    @property
    def last_span_gain(self) -> NDArrayFloat:
        """Net fibre gain of the last evaluated span, model order."""
        return np.ascontiguousarray(self._last_span_gain)

    @property
    def last_raman_ase_w(self) -> NDArrayFloat:
        """Newly generated Raman ASE of the last span, model order."""
        return np.ascontiguousarray(self._last_raman_ase_internal[self.inverse_order])

    def clear_span_cache(self) -> None:
        """Clear the parent span cache and the coarse-ODE result cache."""
        super().clear_span_cache()
        self._raman_cache.clear()
        self._resolution_result_cache.clear()

    # -- 2019b 调制格式修正 -------------------------------------------------
    def attach_modulation_format_reference(self, reference: Semrau2019SpanKernel) -> None:
        """Attach the 2019b reference kernel that supplies the XCI ratio.

        The ratio ``XPM(Phi)/XPM(0)`` is taken from the ``semrau2019`` kernel
        built with the *same* channel plan, fibre and per-span power, so the
        correction is exactly the 2019b one instead of a re-derivation.  The
        kernel is only created by the model when
        ``modulation_format_correction=True``; the default never calls this.

        Args:
            reference: ``semrau2019`` span kernel built with ``egn=True`` and
                the requested ``excess_kurtosis``.
        """
        if reference.matrices.mat_w.size == 0:
            raise ValueError("the modulation-format reference kernel must be built with egn=True.")
        self._mf_reference = reference
        self._mf_ratio_cache = None

    def modulation_format_ratio(
        self,
        power_in_w: NDArrayFloat,
        span_length_m: float,
        n_spans: int,
    ) -> NDArrayFloat:
        """Per-channel XCI correction ratio of the 2019b format correction.

        ``r_i = XPM_i(Phi) / XPM_i(0)`` with both terms evaluated by the
        ``semrau2019`` kernel at the same per-span power profile and the same
        span count.  It carries both terms of 2019b Eq. (16): the statistical
        ``1 + 5Phi/(6n)`` factor and the ``(5/3)Phi*pi`` asymptotic term.  For
        single-channel plans (no XPM) the ratio is exactly 1.

        Args:
            power_in_w: ``(N,)`` launch power per channel (W), model order.
            span_length_m: Span length (m).
            n_spans: Number of spans of the link.

        Returns
        -------
            ``(N,)`` ratio, model order; 1 where the reference XPM is zero.
        """
        reference = self._mf_reference
        if reference is None:
            raise RuntimeError(
                "modulation format ratio requested without an attached semrau2019 reference kernel."
            )
        power = np.ascontiguousarray(np.asarray(power_in_w, dtype=np.float64))
        key = (float(span_length_m), int(max(1, int(n_spans))))
        cached = self._mf_ratio_cache
        if cached is not None and cached[0] == key and np.array_equal(cached[1], power):
            return cached[2]

        matrices = reference.matrices
        tail = (
            reference.alpha_npm,
            reference.f_rel_hz,
            reference.b_hz,
            matrices.spm_u,
            matrices.spm_v,
            matrices.spm_coef,
            matrices.mat_u,
            matrices.mat_v,
            matrices.mat_w,
        )
        _, _, xpm_reference = semrau_span_jit(
            power,
            key[0],
            key[1],
            reference.srs_cr_w_m_hz,
            reference.excess_kurtosis,
            0.0,
            True,
            *tail,
        )
        _, _, xpm_gaussian = semrau_span_jit(
            power,
            key[0],
            key[1],
            reference.srs_cr_w_m_hz,
            0.0,
            0.0,
            True,
            *tail,
        )
        ratio = np.ones_like(power)
        positive = xpm_gaussian > 0.0
        ratio[positive] = xpm_reference[positive] / xpm_gaussian[positive]
        self._mf_ratio_cache = (key, np.array(power, dtype=np.float64, copy=True), ratio)
        return ratio

    def _solver_for(self, span_length_m: float) -> RamanPaperSpanSolver:
        """Return the coupled-ODE solver of a span length (cached)."""
        key = int(round(span_length_m * 1e6))
        solver = self._solver_cache.get(key)
        if solver is not None:
            return solver
        solver = self._build_solver(span_length_m, self.raman_steps)
        self._solver_cache[key] = solver
        return solver

    def _build_solver(self, span_length_m: float, n_steps: int) -> RamanPaperSpanSolver:
        """Build a coupled-ODE solver for one span length and step count."""
        pump_frequencies = np.asarray(
            [C_LIGHT / (float(pump.wavelength_nm) * 1e-9) for pump in self._raman_pumps],
            dtype=np.float64,
        )
        pump_lambdas = C_LIGHT / pump_frequencies
        pump_a_eff = _calc_aeff_dynamic(
            pump_lambdas,
            self._fiber_config.effective_area_um2_ref,
            self._fiber_config.aeff_slope_um2_nm,
            self._fiber_config.reference_wavelength_nm,
        )
        pump_alpha = np.asarray(
            [float(pump.attenuation_db_per_km) * np.log(10.0) / 10.0 / 1e3 for pump in self._raman_pumps],
            dtype=np.float64,
        )
        self._pump_alpha_npm = pump_alpha
        return RamanPaperSpanSolver(
            self.f_abs_hz,
            self.b_hz,
            self._raman_pumps,
            float(span_length_m),
            self.alpha_npm,
            self.a_eff_m2,
            pump_alpha,
            pump_a_eff,
            self._raman_gain_model,
            n_steps=n_steps,
            n_iterations=self.raman_iterations,
            include_isrs=self.include_isrs,
            include_ase=self._raman_ase,
            pump_depletion=self.pump_depletion,
            signal_polarizations=self.signal_polarizations,
            pump_pump_raman=self.pump_pump_raman,
            launch_power_convention=self.launch_power_convention,
            lumped_loss=self.lumped_loss or None,
        )

    def _resolution_solver_for(self, span_length_m: float, n_steps: int) -> RamanPaperSpanSolver:
        """Return (and cache) the finer solver used by the opt-in audit.

        It is cached separately from :attr:`_solver_cache` because that cache
        is keyed by span length only.  The audit never touches the solved-step
        solver, so its entries cannot change the point result.
        """
        key = (int(round(span_length_m * 1e6)), int(n_steps))
        solver = self._resolution_solver_cache.get(key)
        if solver is None:
            solver = self._build_solver(span_length_m, int(n_steps))
            self._resolution_solver_cache[key] = solver
        return solver

    def _resolution_result(
        self,
        power_internal: NDArrayFloat,
        span_length_m: float,
        n_steps: int,
    ) -> PaperRamanSpanResult:
        """Solve and memoise one finer-step result for the resolution audit."""
        key = int(round(span_length_m * 1e6))
        for cached_power, cached_key, cached_steps, cached_result in self._resolution_result_cache:
            if cached_key != key or cached_steps != int(n_steps):
                continue
            if np.array_equal(cached_power, power_internal) or np.allclose(
                cached_power, power_internal, rtol=SPAN_CACHE_RTOL, atol=0.0
            ):
                return cached_result
        solver = self._resolution_solver_for(span_length_m, int(n_steps))
        self.perf_ode_solves += 1
        result = solver.solve(power_internal, None)
        if len(self._resolution_result_cache) >= SPAN_CACHE_MAX_ENTRIES:
            self._resolution_result_cache.pop(0)
        self._resolution_result_cache.append(
            (
                np.array(power_internal, dtype=np.float64, copy=True),
                key,
                int(n_steps),
                result,
            )
        )
        return result

    def _resolution_audit(
        self,
        power_internal: NDArrayFloat,
        span_length_m: float,
        coarse: PaperRamanSpanResult,
        active: NDArrayBool,
    ) -> tuple[bool, int, float, bool]:
        """Run the bounded step-doubling audit of one span.

        The ladder compares the solved result with ``2x`` the step count, then
        ``4x`` and so on up to :data:`RAMAN_RESOLUTION_MAX_STEPS`, always
        against the *solved* result.  A doubling can look fine while a larger
        jump does not, so stopping at the first doubling would hide the AJ
        failure mode.  The full bounded ladder is always walked, so the
        reported change is the worst one against the finest checked tier, not
        merely the first value above the tolerance.

        Args:
            power_internal: ``(N,)`` launch power, internal channel order.
            span_length_m: Span length (m).
            coarse: Result at the solved step count.
            active: ``(N,)`` launched-channel mask, internal order.

        Returns
        -------
            ``(under_resolved, check_steps, change, checked)``.  ``checked`` is
            ``False`` when no finer solve could be compared (cap reached or a
            finer solve did not converge), which keeps a non-converged control
            solve from raising a false alarm.
        """
        current = int(self.raman_steps)
        if current >= RAMAN_RESOLUTION_MAX_STEPS:
            return False, 0, 1.0, False
        next_steps = min(2 * current, RAMAN_RESOLUTION_MAX_STEPS)
        checked = False
        worst_change = 0.0
        worst_steps = 0
        while next_steps > current:
            fine = self._resolution_result(power_internal, span_length_m, next_steps)
            if not self._raman_solve_is_usable(fine):
                # A non-converged control solve is not evidence of anything.
                return False, 0, 1.0, False
            checked = True
            change = _raman_resolution_change(coarse, fine, power_internal, active)
            if change > worst_change:
                worst_change = change
                worst_steps = next_steps
            if next_steps >= RAMAN_RESOLUTION_MAX_STEPS:
                break
            next_steps = min(2 * next_steps, RAMAN_RESOLUTION_MAX_STEPS)
        under_resolved = checked and worst_change > self.raman_resolution_tol
        return under_resolved, worst_steps, float(worst_change), checked


    def _raman_result(self, power_internal: NDArrayFloat, span_length_m: float) -> PaperRamanSpanResult:
        """Solve (or reuse) the coarse coupled ODE of one span state.

        The solve is memoised with the same relative tolerance the parent uses
        for its span cache, so the identical transparent spans of a link share
        one solve.  The input ASE is deliberately zero: the newly generated
        spontaneous ASE is independent of it and the accumulated ASE is carried
        by the route layer.
        """
        key = int(round(span_length_m * 1e6))
        for cached_power, cached_key, cached_result in self._raman_cache:
            if cached_key != key:
                continue
            if np.array_equal(cached_power, power_internal) or np.allclose(
                cached_power, power_internal, rtol=SPAN_CACHE_RTOL, atol=0.0
            ):
                return cached_result
        solver = self._solver_for(span_length_m)
        self.perf_ode_solves += 1
        result = solver.solve(power_internal, None)
        if len(self._raman_cache) >= SPAN_CACHE_MAX_ENTRIES:
            self._raman_cache.pop(0)
        self._raman_cache.append(
            (
                np.array(power_internal, dtype=np.float64, copy=True),
                key,
                result,
            )
        )
        return result

    def _validity_tilt_db(self, power_tilt_db: float, gain_tilt_db: float) -> float:
        """Include the pump-induced gain tilt in the validity flag.

        With active pumps the span gain is no longer the ISRS-only profile of
        the base PCFM: the pump deposits gain over the comb and its tilt is
        the quantity the strong-tilt audit identifies as the limit of the
        polynomial profile.  Without pumps the parent criterion is kept, so
        the no-pump report is identical to :class:`PCFMSpanKernel`.

        Args:
            power_tilt_db: Launch-power tilt ``10 log10(max/min)`` (dB).
            gain_tilt_db: Span-gain tilt ``10 log10(max/min)`` (dB).

        Returns
        -------
            The larger of the two tilts when pumps are active, otherwise the
            launch-power tilt.
        """
        if self.active:
            return max(power_tilt_db, gain_tilt_db)
        return power_tilt_db

    @staticmethod
    def _raman_solve_is_usable(result: PaperRamanSpanResult) -> bool:
        """Return whether every array of a coupled solve is finite and converged.

        The fixed-point flag alone is not sufficient: a forward-pump solve has
        no fixed point, yet an under-resolved RK4 step can still return a
        finite-but-wrong profile.  The auto rule handles the known E/S
        multi-pump case; this predicate is the last-resort guard that keeps a
        non-finite (or non-converged) solve from being reported as usable.

        Args:
            result: Result of :class:`RamanPaperSpanSolver`.

        Returns
        -------
            ``True`` when the solve converged and every output array is finite.
        """
        if not result.converged:
            return False
        return bool(
            np.all(np.isfinite(result.profile_norm))
            and np.all(np.isfinite(result.power_out_w))
            and np.all(np.isfinite(result.raman_ase_w))
            and np.all(np.isfinite(result.pump_power_out_w))
        )

    def validity_report(
        self,
        span_length_m: float,
        power_in_w: NDArrayFloat,
        *,
        power_out_w: NDArrayFloat | None = None,
    ) -> SpanValidityReport:
        """Add the pump direction, depletion and Raman convergence to the report.

        The coupled solve already returns the pump power at each pump's exit
        face, so the depletion is read from the same state that produced the
        NLI profile.  A non-converged or non-finite solve invalidates every
        active channel: the reported NLI/profile is not a solution, so a
        downstream ``strict`` mode or the error budget must refuse it.  The
        S/E multi-pump regime is also flagged independently, even when the
        solve is converged, so the caller can see that the default needed the
        extended step count.

        A pump inside the occupied signal band is a separate, physical
        invalidity: it is not a DRA configuration at all, so every active
        channel is reported invalid regardless of convergence.  The point
        NLI/ASE/SNR is not touched; only the report (and therefore the
        ``strict`` mode and the error budget) refuses it.

        With no active pump the parent report is returned unchanged (empty
        pump arrays), which keeps the no-pump diagnostics bit-for-bit
        identical to :class:`PCFMSpanKernel`.

        Args:
            span_length_m: Span length (m).
            power_in_w: ``(N,)`` launch power per channel (W), model order.
            power_out_w: Optional ``(N,)`` span-end signal power, model order.

        Returns
        -------
            The :class:`SpanValidityReport`, with ``pump_active`` set when the
            kernel carries positive-power pumps.
        """
        report = super().validity_report(span_length_m, power_in_w, power_out_w=power_out_w)
        if not self.active:
            return self._with_lumped_loss_report(report)
        power = np.asarray(power_in_w, dtype=np.float64)[self.order]
        result = self._raman_result(np.ascontiguousarray(power), float(span_length_m))
        if self._pump_alpha_npm is None:
            self._solver_for(float(span_length_m))
        pump_in = np.asarray([float(pump.power_w) for pump in self._raman_pumps], dtype=np.float64)
        pump_passive = pump_in * np.exp(-self._pump_alpha_npm * float(span_length_m))
        depletion = np.clip(1.0 - result.pump_power_out_w / pump_passive, 0.0, 1.0)
        directions = tuple(str(pump.direction) for pump in self._raman_pumps)

        usable = self._raman_solve_is_usable(result)
        active = np.asarray(power_in_w, dtype=np.float64) > 0.0
        # Opt-in, read-only resolution audit.  It only fills the report fields
        # below; it never feeds back into the profile, NLI, ASE or SNR.
        resolution_checked = False
        resolution_steps = 0
        resolution_change = 1.0
        auto_under_resolved = False
        if self.raman_resolution_check:
            (
                auto_under_resolved,
                resolution_steps,
                resolution_change,
                resolution_checked,
            ) = self._resolution_audit(
                np.ascontiguousarray(power),
                float(span_length_m),
                result,
                power > 0.0,
            )
        flagged = np.array(report.flagged, dtype=bool, copy=True)
        valid = np.array(report.valid, dtype=bool, copy=True)
        confidence = np.array(report.confidence, dtype=np.float64, copy=True)
        if self._wideband_multipump:
            flagged = np.where(active, True, flagged)
            confidence = np.where(active, np.minimum(confidence, 0.8), confidence)
        if not usable:
            flagged = np.where(active, True, flagged)
            valid = np.where(active, False, valid)
            confidence = np.where(active, np.minimum(confidence, 0.2), confidence)

        # 泵落在活跃信号带内不是“收敛风险”，而是物理配置错误：整个 span 的
        # 数据信道都被泵污染，无法用任何步数修好。硬失效，与收敛无关。
        pump_overlap, min_offset = _pump_signal_overlap(
            self._pump_frequencies_hz,
            self.f_abs_hz,
            self.b_hz,
            power > 0.0,
            self._pump_signal_overlap_guard_hz,
        )
        overlap_channels = active & pump_overlap
        if pump_overlap:
            flagged = np.where(active, True, flagged)
            valid = np.where(active, False, valid)
            confidence = np.where(active, np.minimum(confidence, 0.2), confidence)
            if not self._pump_overlap_warned:
                self._pump_overlap_warned = True
                wavelengths = ", ".join(f"{float(pump.wavelength_nm):g}" for pump in self._raman_pumps)
                band = _occupied_signal_band(
                    self.f_abs_hz,
                    self.b_hz,
                    power > 0.0,
                    self._pump_signal_overlap_guard_hz,
                )
                # ``pump_overlap`` 为真时 band 一定存在；写出显式分支只是为了类型收窄。
                band_low, band_high = band if band is not None else (float("nan"), float("nan"))
                warnings.warn(
                    "pcfm_h3_raman: at least one Raman pump falls inside the occupied signal "
                    f"band ({band_low / 1e12:.3f}-{band_high / 1e12:.3f} THz including a "
                    f"{self._pump_signal_overlap_guard_hz / 1e9:g} GHz guard; pumps at "
                    f"{wavelengths} nm). "
                    "A pump inside the data band cannot be separated from the signals, so this "
                    "is not a physical DRA configuration. The span is reported invalid by "
                    "validity_report and the error budget; the point NLI/ASE/SNR is unchanged. "
                    "Remove or move the in-band pump.",
                    RuntimeWarning,
                    stacklevel=2,
                )

        return replace(
            report,
            pump_active=True,
            pump_directions=directions,
            pump_depletion=np.ascontiguousarray(depletion),
            pump_depletion_max=float(np.max(depletion)) if depletion.size else 0.0,
            flagged=np.ascontiguousarray(flagged),
            valid=np.ascontiguousarray(valid),
            confidence=np.ascontiguousarray(confidence),
            raman_converged=bool(result.converged),
            raman_steps=int(self.raman_steps),
            raman_wideband_multipump=bool(self._wideband_multipump),
            raman_pump_signal_overlap=bool(pump_overlap),
            raman_pump_overlap_channels=np.ascontiguousarray(overlap_channels),
            raman_pump_min_offset_hz=float(min_offset),
            lumped_loss_positions_m=np.ascontiguousarray(
                [position for position, _ in self.lumped_loss], dtype=np.float64
            ),
            lumped_loss_db=np.ascontiguousarray([loss for _, loss in self.lumped_loss], dtype=np.float64),
            lumped_loss_in_ode=bool(self.lumped_loss_in_ode),
            lumped_loss_segments=int(self.lumped_loss_segments),
            raman_auto_under_resolved=bool(auto_under_resolved),
            raman_resolution_check_steps=int(resolution_steps),
            raman_resolution_change=float(resolution_change),
            raman_resolution_checked=bool(resolution_checked),
        )

    def _with_lumped_loss_report(self, report: SpanValidityReport) -> SpanValidityReport:
        """Attach the static lumped-loss diagnostics to a pump-free report.

        Without a configured element the report object is returned unchanged,
        so the pump-free diagnostics of a span that does not use the new option
        stay identical to :class:`PCFMSpanKernel`.
        """
        if not self.lumped_loss:
            return report
        return replace(
            report,
            lumped_loss_positions_m=np.ascontiguousarray(
                [position for position, _ in self.lumped_loss], dtype=np.float64
            ),
            lumped_loss_db=np.ascontiguousarray([loss for _, loss in self.lumped_loss], dtype=np.float64),
            lumped_loss_in_ode=False,
            lumped_loss_segments=int(self.lumped_loss_segments),
        )

    def _resample_profile(
        self,
        profile: NDArrayFloat,
        span_length_m: float,
        sample_positions: NDArrayFloat | None = None,
    ) -> NDArrayFloat:
        """Linearly resample the coarse profile onto the PCFM fit grid.

        The coarse solve samples the profile twice per RK4 step.  Without
        lumped loss those positions are uniform and the map is the historical
        one; with lumped loss the RK4 steps are allocated per segment, so the
        sample positions are non-uniform and must be passed explicitly.  The
        PCFM polynomial fit uses ``self.spp_steps`` samples, which may be a
        different count, so the resampling keeps the two independent.

        Args:
            profile: ``(S, N)`` normalised profile of the coupled solve.
            span_length_m: Span length (m).
            sample_positions: ``(S,)`` normalised ``z/L`` of every row, or
                ``None`` for the historical uniform ``k/(2*n_steps)`` grid.

        Returns
        -------
            ``(S_target, N)`` profile on the PCFM fit grid.
        """
        target = self._sample_positions(span_length_m)
        n_source = profile.shape[0]
        if sample_positions is None:
            if target.size == n_source:
                return np.ascontiguousarray(profile)
            # The coarse solve samples the profile at the midpoint and the end
            # of every step; the first sample is at 0.5/n, not at 0.  Add the
            # exact u=0 value (the normalised profile is 1 there) so that a
            # PCFM grid with more steps does not extrapolate backwards.
            source = np.empty(n_source + 1, dtype=np.float64)
            source[0] = 0.0
            source[1:] = np.arange(1, n_source + 1, dtype=np.float64) / n_source
        else:
            # 分段网格：位置由求解器给出，首点补 u=0（归一化剖面在 0 处为 1）。
            source = np.concatenate(
                (np.zeros(1, dtype=np.float64), np.asarray(sample_positions, dtype=np.float64))
            )
        extended = np.vstack([np.ones((1, profile.shape[1]), dtype=np.float64), profile])
        index = np.searchsorted(source, target, side="right") - 1
        index = np.clip(index, 0, source.size - 2)
        weight = (target - source[index]) / (source[index + 1] - source[index])
        resampled = (1.0 - weight)[:, None] * extended[index] + weight[:, None] * extended[index + 1]
        return np.ascontiguousarray(resampled)

    def _spp_drive_scale(self) -> float:
        """Return the ISRS drive scale from the *launch* convention, not the NLI one.

        The two can differ on purpose in H3: an explicit
        ``nli_power_convention="total"`` under a per-polarization launch keeps
        the legacy 8x-low NLI as a comparison control, while the physical ISRS
        profile must still be driven by the dual-polarization total power.  The
        base class therefore keys off the NLI convention, which is only the
        right answer when both follow the launch.

        Returns
        -------
            ``2.0`` for a per-polarization launch, ``1.0`` otherwise (which
            includes the historical ``total`` + ``signal_polarizations=2``
            double-drive probe and keeps it unchanged).
        """
        return 2.0 if self.launch_power_convention == "per_pol" else 1.0

    def _integrate_spp(
        self,
        power: NDArrayFloat,
        span_length_m: float,
    ) -> tuple[NDArrayFloat, NDArrayFloat]:
        """Return the normalised SPP and the span-end power.

        With active pumps the profile is the coupled signal/pump solution, whose
        coupling drive already carries ``signal_polarizations``.  With no active
        pump the parent ISRS-only integration is used; it applies
        :meth:`_spp_drive_scale` itself, so a per-polarization launch is driven
        by the physical total power without a second scaling here.

        Args:
            power: ``(N,)`` launch power per channel (W), internal order.
            span_length_m: Span length (m).

        Returns
        -------
            ``(profile_norm, power_out)`` with the same meaning as the parent.
        """
        if not self.active:
            return super()._integrate_spp(power, span_length_m)
        result = self._raman_result(power, span_length_m)
        return (
            self._resample_profile(result.profile_norm, span_length_m, result.sample_positions_u),
            np.ascontiguousarray(result.power_out_w),
        )

    def evaluate(
        self,
        power_in_w: NDArrayFloat,
        span_length_m: float,
        n_effective_spans: int = 1,
        *,
        span_index: int = 0,
        beta2_accum_ps2: NDArrayFloat | None = None,
        span_context: SpanContext | None = None,
    ) -> SpanFiberOutput:
        """Evaluate one span, exposing the Raman ASE of the same coarse solve.

        The parent :meth:`PCFMSpanKernel.evaluate` owns the NLI, the EGN
        correction and the inter-span phase.  This override only prepares the
        Raman ASE (which the parent does not know about) and then delegates, so
        the no-pump branch is exactly the parent implementation.

        Args:
            power_in_w: ``(N,)`` launch power per channel (W), model order.
            span_length_m: Span length (m).
            n_effective_spans: Kept for protocol compatibility.
            span_index: Index of the span in the link.
            beta2_accum_ps2: Accumulated dispersion at the span input (ps^2).
            span_context: Position of the span in the link.

        Returns
        -------
            The span output, including the Raman-aware NLI.
        """
        if not self.active:
            self._last_raman_ase_internal = np.zeros(self.n_nodes, dtype=np.float64)
            self.last_raman_iterations = 0
            self.last_raman_converged = True
            self.last_pump_power_out_w = None
            output = super().evaluate(
                power_in_w,
                span_length_m,
                n_effective_spans,
                span_index=span_index,
                beta2_accum_ps2=beta2_accum_ps2,
                span_context=span_context,
            )
            self._record_span_gain(power_in_w, output)
            return output
        power = np.ascontiguousarray(np.asarray(power_in_w, dtype=np.float64)[self.order])
        result = self._raman_result(power, span_length_m)
        if self._raman_ase:
            self._last_raman_ase_internal = np.ascontiguousarray(result.raman_ase_w)
        else:
            self._last_raman_ase_internal = np.zeros(self.n_nodes, dtype=np.float64)
        self.last_raman_iterations = int(result.iterations)
        self.last_raman_converged = bool(result.converged)
        self.last_pump_power_out_w = np.ascontiguousarray(result.pump_power_out_w)
        if not self._raman_solve_is_usable(result):
            warnings.warn(
                "pcfm_h3_raman: the coupled signal/pump solve is not usable "
                f"(converged={bool(result.converged)}, raman_steps={self.raman_steps}, "
                f"wideband_multipump={bool(self._wideband_multipump)}). The span is reported "
                "invalid by validity_report and the error budget; do not use its SNR as a "
                "trusted QoT. Increase raman_steps or use the full hybrid model.",
                RuntimeWarning,
                stacklevel=2,
            )
        output = super().evaluate(
            power_in_w,
            span_length_m,
            n_effective_spans,
            span_index=span_index,
            beta2_accum_ps2=beta2_accum_ps2,
            span_context=span_context,
        )
        self._record_span_gain(power_in_w, output)
        return output

    def _record_span_gain(self, power_in_w: NDArrayFloat, output: SpanFiberOutput) -> None:
        """Store the net fibre gain of one evaluated span.

        The route EDFA compensates every channel independently, so the path
        result carries no gain tilt.  The uncertainty layer needs the tilt that
        the Raman/ISRS profile actually produced, hence this side output.

        Args:
            power_in_w: ``(N,)`` span input power, model order.
            output: Span output of the same evaluation.
        """
        power_in = np.asarray(power_in_w, dtype=np.float64)
        self._last_span_gain = np.ascontiguousarray(
            np.divide(
                np.asarray(output.power_out_w, dtype=np.float64),
                power_in,
                out=np.ones_like(power_in),
                where=power_in > 0.0,
            )
        )


