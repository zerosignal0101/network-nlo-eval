#: RK4 steps of the coarse Raman profile/ASE solve.
#:
#: The full paper model uses 32 steps.  At 12 steps the pump gain, the profile
#: shape and the Raman ASE of the C-band benchmark are within 0.05 dB of the
#: 32-step solve, while the cost is roughly halved.  The model is explicit
#: about this being a coarse solve: it is a fast profile provider, not a
#: replacement for the full paper ODE.
DEFAULT_H3_RAMAN_STEPS: int = 12

#: Fixed-point iterations cap of the backward-pump solve.  The solver stops as
#: soon as the relative pump change falls below its tolerance, so the cap only
#: matters for heavily depleted backward-pumped spans.
DEFAULT_H3_RAMAN_ITERATIONS: int = DEFAULT_FIXED_POINT_ITERATIONS


def _active_pumps(pumps: Sequence[RamanPumpConfig] | None) -> list[RamanPumpConfig]:
    """Return the pumps that carry positive power.

    Args:
        pumps: Pump list, possibly ``None`` or containing zero-power entries.

    Returns
    -------
        A new list with only the pumps of positive power.
    """
    if not pumps:
        return []
    return [pump for pump in pumps if float(pump.power_w) > 0.0]


class PCFH3RamanSpanKernel(PCFMSpanKernel):
    """PCFM kernel whose SPP is the coupled signal/pump profile of one span.

    The class inherits the SCI/XCI kernels, the edge fix, the polynomial fit and
    the span memoisation of :class:`PCFMSpanKernel`.  It overrides only the
    profile provider: with active pumps the normalised SPP comes from a coarse
    coupled-ODE solve, and the same solve supplies the Raman ASE.  With no
    active pump every call falls through to the parent, which is what makes the
    no-pump path bit-for-bit identical to H3 PCFM.

    Args:
        f_abs_hz: ``(N,)`` channel centre frequencies (Hz).
        b_hz: ``(N,)`` channel bandwidths (Hz).
        fiber_config: Fibre parameters of the span.
        pumps: Pumps applied to the span; only positive-power pumps are used.
        gain_model: Raman gain spectrum model.
        raman_ase: Expose the newly generated Raman ASE to the route layer.
        raman_steps: RK4 steps of the coarse signal/pump/ASE solve.
        raman_iterations: Fixed-point iterations cap of the backward-pump solve.
        include_isrs: Include channel-channel ISRS in the coupled solve.
        **kwargs: Forwarded to :class:`PCFMSpanKernel`.
    """

    def __init__(
        self,
        f_abs_hz: NDArrayFloat,
        b_hz: NDArrayFloat,
        fiber_config: FiberSpanConfig,
        *,
        pumps: Sequence[RamanPumpConfig] | None = None,
        gain_model: RamanGainModel,
        raman_ase: bool = True,
        raman_steps: int = DEFAULT_H3_RAMAN_STEPS,
        raman_iterations: int = DEFAULT_H3_RAMAN_ITERATIONS,
        include_isrs: bool = True,
        **kwargs: object,
    ) -> None:
        """Build the kernel and cache the pump-side constants.

        Raises
        ------
            ValueError: ``raman_steps`` or ``raman_iterations`` is not positive.
        """
        if int(raman_steps) < 4:
            raise ValueError(f"raman_steps must be >= 4, got {raman_steps}.")
        if int(raman_iterations) < 1:
            raise ValueError(f"raman_iterations must be >= 1, got {raman_iterations}.")
        super().__init__(f_abs_hz, b_hz, fiber_config, **kwargs)  # type: ignore[arg-type]
        self._fiber_config = fiber_config
        self._raman_pumps = _active_pumps(pumps)
        self._raman_gain_model = gain_model
        self._raman_ase = bool(raman_ase)
        self.raman_steps = int(raman_steps)
        self.raman_iterations = int(raman_iterations)
        self.include_isrs = bool(include_isrs)
        self._solver_cache: dict[int, RamanPaperSpanSolver] = {}
        self._raman_cache: list[tuple[NDArrayFloat, int, PaperRamanSpanResult]] = []
        self._last_raman_ase_internal = np.zeros(self.n_nodes, dtype=np.float64)
        self.last_raman_iterations = 0
        self.last_raman_converged = True
        self.last_pump_power_out_w: NDArrayFloat | None = None

    @property
    def active(self) -> bool:
        """Whether at least one pump carries positive power."""
        return bool(self._raman_pumps)

    @property
    def last_raman_ase_w(self) -> NDArrayFloat:
        """Newly generated Raman ASE of the last span, model order."""
        return np.ascontiguousarray(self._last_raman_ase_internal[self.inverse_order])

    def clear_span_cache(self) -> None:
        """Clear the parent span cache and the coarse-ODE result cache."""
        super().clear_span_cache()
        self._raman_cache.clear()

    def _solver_for(self, span_length_m: float) -> RamanPaperSpanSolver:
        """Return the coupled-ODE solver of a span length (cached)."""
        key = int(round(span_length_m * 1e6))
        solver = self._solver_cache.get(key)
        if solver is not None:
            return solver
        pump_frequencies = np.asarray(
            [C_LIGHT / (float(pump.wavelength_nm) * 1e-9) for pump in self._raman_pumps],
            dtype=np.float64,
        )
        pump_lambdas = C_LIGHT / pump_frequencies
        pump_a_eff = _calc_aeff_dynamic(
            pump_lambdas,
            self._fiber_config.effective_area_um2_ref,
            self._fiber_config.aeff_slope_um2_nm,
            self._fiber_config.reference_wavelength_nm,
        )
        pump_alpha = np.asarray(
            [float(pump.attenuation_db_per_km) * np.log(10.0) / 10.0 / 1e3 for pump in self._raman_pumps],
            dtype=np.float64,
        )
        solver = RamanPaperSpanSolver(
            self.f_abs_hz,
            self.b_hz,
            self._raman_pumps,
            float(span_length_m),
            self.alpha_npm,
            self.a_eff_m2,
            pump_alpha,
            pump_a_eff,
            self._raman_gain_model,
            n_steps=self.raman_steps,
            n_iterations=self.raman_iterations,
            include_isrs=self.include_isrs,
            include_ase=self._raman_ase,
        )
        self._solver_cache[key] = solver
        return solver

    def _raman_result(self, power_internal: NDArrayFloat, span_length_m: float) -> PaperRamanSpanResult:
        """Solve (or reuse) the coarse coupled ODE of one span state.

        The solve is memoised with the same relative tolerance the parent uses
        for its span cache, so the identical transparent spans of a link share
        one solve.  The input ASE is deliberately zero: the newly generated
        spontaneous ASE is independent of it and the accumulated ASE is carried
        by the route layer.
        """
        key = int(round(span_length_m * 1e6))
        for cached_power, cached_key, cached_result in self._raman_cache:
            if cached_key != key:
                continue
            if np.array_equal(cached_power, power_internal) or np.allclose(
                cached_power, power_internal, rtol=SPAN_CACHE_RTOL, atol=0.0
            ):
                return cached_result
        solver = self._solver_for(span_length_m)
        result = solver.solve(power_internal, None)
        if len(self._raman_cache) >= SPAN_CACHE_MAX_ENTRIES:
            self._raman_cache.pop(0)
        self._raman_cache.append(
            (
                np.array(power_internal, dtype=np.float64, copy=True),
                key,
                result,
            )
        )
        return result

    def _resample_profile(self, profile: NDArrayFloat, span_length_m: float) -> NDArrayFloat:
        """Linearly resample the coarse profile onto the PCFM fit grid.

        The coarse solve samples the profile twice per RK4 step at uniform
        positions.  The PCFM polynomial fit uses ``self.spp_steps`` samples,
        which may be a different count; a linear resampling keeps the two
        independent.  The map is exact when the two step counts coincide.
        """
        target = self._sample_positions(span_length_m)
        n_source = profile.shape[0]
        if target.size == n_source:
            return np.ascontiguousarray(profile)
        # The coarse solve samples the profile at the midpoint and the end of
        # every step; the first sample is at 0.5/n, not at 0.  Add the exact
        # u=0 value (the normalised profile is 1 there) so that a PCFM grid
        # with more steps does not extrapolate backwards.
        source = np.empty(n_source + 1, dtype=np.float64)
        source[0] = 0.0
        source[1:] = np.arange(1, n_source + 1, dtype=np.float64) / n_source
        extended = np.vstack([np.ones((1, profile.shape[1]), dtype=np.float64), profile])
        index = np.searchsorted(source, target, side="right") - 1
        index = np.clip(index, 0, source.size - 2)
        weight = (target - source[index]) / (source[index + 1] - source[index])
        resampled = (1.0 - weight)[:, None] * extended[index] + weight[:, None] * extended[index + 1]
        return np.ascontiguousarray(resampled)

    def _integrate_spp(
        self,
        power: NDArrayFloat,
        span_length_m: float,
    ) -> tuple[NDArrayFloat, NDArrayFloat]:
        """Return the normalised SPP and the span-end power.

        With active pumps the profile is the coupled signal/pump solution.  With
        no active pump the parent ISRS-only integration is used unchanged.

        Args:
            power: ``(N,)`` launch power per channel (W), internal order.
            span_length_m: Span length (m).

        Returns
        -------
            ``(profile_norm, power_out)`` with the same meaning as the parent.
        """
        if not self.active:
            return super()._integrate_spp(power, span_length_m)
        result = self._raman_result(power, span_length_m)
        return self._resample_profile(result.profile_norm, span_length_m), np.ascontiguousarray(result.power_out_w)

    def evaluate(
        self,
        power_in_w: NDArrayFloat,
        span_length_m: float,
        n_effective_spans: int = 1,
        *,
        span_index: int = 0,
        beta2_accum_ps2: NDArrayFloat | None = None,
        span_context: SpanContext | None = None,
    ) -> SpanFiberOutput:
        """Evaluate one span, exposing the Raman ASE of the same coarse solve.

        The parent :meth:`PCFMSpanKernel.evaluate` owns the NLI, the EGN
        correction and the inter-span phase.  This override only prepares the
        Raman ASE (which the parent does not know about) and then delegates, so
        the no-pump branch is exactly the parent implementation.

        Args:
            power_in_w: ``(N,)`` launch power per channel (W), model order.
            span_length_m: Span length (m).
            n_effective_spans: Kept for protocol compatibility.
            span_index: Index of the span in the link.
            beta2_accum_ps2: Accumulated dispersion at the span input (ps^2).
            span_context: Position of the span in the link.

        Returns
        -------
            The span output, including the Raman-aware NLI.
        """
        if not self.active:
            self._last_raman_ase_internal = np.zeros(self.n_nodes, dtype=np.float64)
            self.last_raman_iterations = 0
            self.last_raman_converged = True
            self.last_pump_power_out_w = None
            return super().evaluate(
                power_in_w,
                span_length_m,
                n_effective_spans,
                span_index=span_index,
                beta2_accum_ps2=beta2_accum_ps2,
                span_context=span_context,
            )
        power = np.ascontiguousarray(np.asarray(power_in_w, dtype=np.float64)[self.order])
        result = self._raman_result(power, span_length_m)
        if self._raman_ase:
            self._last_raman_ase_internal = np.ascontiguousarray(result.raman_ase_w)
        else:
            self._last_raman_ase_internal = np.zeros(self.n_nodes, dtype=np.float64)
        self.last_raman_iterations = int(result.iterations)
        self.last_raman_converged = bool(result.converged)
        self.last_pump_power_out_w = np.ascontiguousarray(result.pump_power_out_w)
        return super().evaluate(
            power_in_w,
            span_length_m,
            n_effective_spans,
            span_index=span_index,
            beta2_accum_ps2=beta2_accum_ps2,
            span_context=span_context,
        )


