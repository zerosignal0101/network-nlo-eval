class PCFH3RamanModel(PCFMModel):
    """H3 PCFM with a profile-aware hybrid Raman front end.

    The model is the fast companion of :class:`~network_nlo_eval.models.hybrid_raman.HybridRamanPaperModel`:
    it keeps the PCFM closed-form NLI but replaces the lumped span-end gain
    with the intra-span normalised profile obtained from a coarse coupled ODE.
    It is opt-in: ``pcfm`` and ``raman_lumped`` keep their existing semantics.

    Args:
        grid: Spectrum grid (legacy ``SpectrumGrid`` or ``FlexibleGrid``).
        ref_fiber_config: Reference fibre configuration.
        symbol_rate_hz: Symbol rate (Hz).
        connections: Optional per-connection grid.
        poly_degree: PCFM SPP polynomial degree. Default 3.
        egn: EGN correction. ``"auto"`` (default) disables it when any active
            pump is forward and enables it otherwise; ``True``/``False`` force
            the legacy behaviour.  See the module docstring for the rationale.
        edge_fix: PCFM edge fix. Default True.
        dense_grid_fix: Opt-in overlap-aware XCI correction.  ``False``
            (default) keeps the historic numbers bit-for-bit; ``True`` replaces
            the XCI weight of pairs whose interfering band crosses the CUT
            centre with the exact integral on the actual band.  The H3 kernel
            forwards it unchanged to :class:`PCFMSpanKernel`.
        cache_spans: Memoise identical spans. Default True.
        spp_steps: PCFM SPP RK4 steps or ``"auto"``. Default ``"auto"``.
        raman_pumps: Pumps applied to every span.  When omitted, the pumps of
            each :class:`FiberSpanConfig` are used.
        raman_gain_model: ``"gaussian"`` (default), ``"linear"`` (CZ),
            ``"table"``, a ``.json``/``.csv`` gain table path, or an explicit
            :class:`~network_nlo_eval.models.raman.RamanGainModel` instance
            (``RamanGainModel.from_file(path)``). Loaded once at construction.
        raman_gain_table: ``(offsets_hz, gains)`` normalized gain table used
            when ``raman_gain_model="table"``.  Linear interpolation inside
            the table, zero outside.  The same shape replaces the
            Gaussian/CZ coefficient in the pump-signal and pump-pump blocks of
            the coupled solve.  Mutually exclusive with an instance or a file
            path.
        raman_ase: Expose the Raman ASE before the EDFA.
        raman_temperature_k: Fibre temperature (K).  ``None`` (default) means
            300 K; an explicit value is a calibration override and warns for
            file-backed gain tables, even when it equals 300.0.
        raman_peak_gain_coefficient_m_per_w: Peak local Raman gain rate.
            ``None`` (default) means ``6e-14``; an explicit value is a
            calibration override and warns for file-backed gain tables, even
            when it equals 6e-14.
        raman_steps: RK4 steps of the coarse coupled profile/ASE solve.
        raman_iterations: Backward-pump fixed-point iteration cap.
        raman_resolution_check: Opt-in read-only step-doubling audit of the
            Raman profile/gain/ASE.  ``False`` (default) adds no solve and
            keeps every point value bit-for-bit identical.
        raman_resolution_tol: Relative tolerance (fraction) of the audit.
            Default ``0.005``; must be finite and positive.
        include_isrs: Include channel-channel ISRS in the coupled solve.
        pump_depletion: Let the pumps be depleted by the signals. Default
            ``True``; ``False`` freezes the pumps to their own attenuation
            (undepleted-pump control convention).
        signal_polarizations: Polarizations represented by each ODE signal
            state.  ``1`` (default) keeps the historical per-polarization
            drive; ``2`` uses the dual-polarization total signal power as the
            coupling drive, matching the physical waveform.
        pump_pump_raman: Include pump-pump Raman coupling in the coupled ODE.
            ``True`` (default) keeps the historical behaviour; ``False`` is the
            pump-pump-off control convention of the C+L residual audit.
        launch_power_convention: Declared power convention of ``power_in_w``.
            ``"total"`` (default) keeps the historical per-channel total power
            and is bit-for-bit unchanged.  ``"per_pol"`` declares that the
            input is per-polarization power (physical total = 2x) and requires
            ``signal_polarizations=2``; the ODE state and every output stay
            per-polarization, only the Raman coupling drive takes the
            dual-polarization total.  With a per-polarization launch the
            newly generated EDFA and ROADM booster ASE are also halved once
            (``ase_polarization_scale=0.5``) so that ``signal_power_w``,
            ``spm_noise_w``, ``xpm_noise_w`` and ``ase_noise_w`` are all
            per-polarization quantities; ``snr_db`` is coordinate independent.
            ``"total"`` with ``signal_polarizations=2`` is retained as the
            legacy unit-less multiplier and emits a :class:`UserWarning` at
            construction.
        nli_power_convention: Declared power convention of the NLI kernels.
            ``"auto"`` (default) follows ``launch_power_convention``, so a
            per-polarization launch also drives the GN weights with the
            physical total power and returns per-polarization NLI.  ``"total"``
            keeps the pre-audit NLI under a per-polarization launch as a
            comparison control and also keeps the total-power ASE (a
            deliberately mixed control, not an end-to-end coordinate);
            ``"per_pol"`` under a total-power launch is rejected.
        pump_signal_overlap_guard_hz: Guard added to each side of the channel
            band edges when deciding whether a pump falls inside the occupied
            signal band.  ``0`` (default) keeps the literal band and the round-Y
            point values; a positive value widens the band for the pump
            linewidth / WDM transition, a negative one shrinks it.  It only
            changes the validity report.
        lumped_loss: Lumped loss elements inside every span, as
            ``(position_m, loss_db)`` pairs (connectors, splices, discrete
            attenuators; PCFM 2026 Section IV-D).  Positions must be strictly
            inside ``(0, L)`` of the fibre, the loss must be non-negative, and
            duplicate positions are merged by summing their dB.  ``None``
            (default) leaves every number bit-for-bit unchanged.  The list is
            forwarded to :class:`PCFH3RamanSpanKernel`, which hands it to the
            base PCFM SPP when the span has no active pump and applies it
            inside the coupled Raman ODE (signal, forward pump, ASE, and the
            backward pump at the same physical ``s = L - z`` position) when it
            has one.  See also the ``lumped_loss_*`` fields of
            :meth:`PCFH3RamanSpanKernel.validity_report`.
        span_coherence: ``"auto"`` (default) uses ``"incoherent"`` for pumped
            links and ``"pcfm"`` for unpumped links; ``"pcfm"`` keeps the H3
            visibility-weighted coherent accumulation; ``"incoherent"`` sums
            the span NLI powers, the paper's ``epsilon=0`` convention.
            The no-pump bit-identity claim applies to the default.
        validity_mode: ``"warn"`` (default) records the per-channel
            applicability report of every span without changing any value;
            ``"strict"`` additionally sets the SNR of invalid channels to
            ``NaN``.  See :meth:`PCFH3RamanSpanKernel.validity_report`.
        modulation_format_correction: Opt-in Semrau 2019b modulation-format
            correction of the XCI term.  ``False`` (default) leaves every
            number bit-for-bit unchanged.  ``True`` multiplies the per-span
            XCI by the 2019b XPM ratio ``XPM(Phi)/XPM(0)`` of the
            ``semrau2019`` kernel evaluated at the same channel plan, fibre
            and per-span power profile; the SCI term is not touched because
            2019b corrects XPM only.  Rejected together with a resolved
            ``egn=True`` (two corrections of the same gap).  See
            ``H3_TASK_REPORT.md`` for the audit and the residual measurement.
        excess_kurtosis: Excess kurtosis ``Phi`` of the modulation format
            (2019b Table I), used only when
            ``modulation_format_correction=True``.  ``0.0`` (default) is the
            identity correction.  The physical range is ``[-2, 100]``;
            negative values are normal for real QAM (16-QAM -0.680,
            64-QAM -0.619, 256-QAM -0.605).  Non-finite or out-of-range values
            raise ``ValueError``.
        **route_options: Forwarded to :class:`~network_nlo_eval.models.route.RouteModel`.

    Raises
    ------
        ValueError: A Raman option, ``egn``, ``excess_kurtosis`` or the
            ``modulation_format_correction``/``egn`` combination is invalid.
    """

    info = H3_RAMAN_MODEL_INFO

    def __init__(
        self,
        grid,
        ref_fiber_config: FiberSpanConfig,
        symbol_rate_hz: float = 50e9,
        connections=None,
        poly_degree: int = 3,
        egn: bool | str = "auto",
        edge_fix: bool = True,
        cache_spans: bool = True,
        spp_steps: int | str = "auto",
        raman_pumps: Sequence[RamanPumpConfig] | None = None,
        raman_gain_model: str | RamanGainModel = "gaussian",
        raman_gain_table: tuple[Sequence[float], Sequence[float]] | None = None,
        raman_ase: bool = True,
        raman_temperature_k: float | None = None,
        raman_peak_gain_coefficient_m_per_w: float | None = None,
        raman_steps: int | str = "auto",
        raman_iterations: int = DEFAULT_H3_RAMAN_ITERATIONS,
        raman_resolution_check: bool = False,
        raman_resolution_tol: float = DEFAULT_RAMAN_RESOLUTION_TOL,
        include_isrs: bool = True,
        pump_depletion: bool = True,
        signal_polarizations: int = 1,
        pump_pump_raman: bool = True,
        launch_power_convention: str = "total",
        nli_power_convention: str = "auto",
        pump_signal_overlap_guard_hz: float = PUMP_SIGNAL_OVERLAP_GUARD_HZ,
        span_coherence: str = "auto",
        validity_mode: str = "warn",
        resolution: str | None = None,
        dense_grid_fix: bool = False,
        lumped_loss: Sequence[tuple[float, float]] | None = None,
        modulation_format_correction: bool = False,
        excess_kurtosis: float = 0.0,
        **route_options: object,
    ) -> None:
        """Build the model and remember the Raman options of the kernels."""
        if isinstance(raman_steps, str):
            if raman_steps != "auto":
                raise ValueError(f"raman_steps must be an integer or 'auto', got {raman_steps!r}.")
        elif int(raman_steps) < 4:
            raise ValueError(f"raman_steps must be >= 4, got {raman_steps}.")
        # 分辨率档位在这里解析：raman_steps 是本类的旋钮，父类不认识它。
        profile = resolve_resolution_profile(resolution)
        quadrature_points = XCI_EDGE_QUADRATURE_POINTS
        if profile is not None:
            if "spp_steps" in profile:
                if spp_steps != "auto":
                    raise ValueError(
                        f"resolution={resolution!r} sets spp_steps={profile['spp_steps']}, but "
                        f"spp_steps={spp_steps!r} was also given explicitly."
                    )
                spp_steps = profile["spp_steps"]
            if "raman_steps" in profile:
                if raman_steps != "auto":
                    raise ValueError(
                        f"resolution={resolution!r} sets raman_steps={profile['raman_steps']}, but "
                        f"raman_steps={raman_steps!r} was also given explicitly."
                    )
                raman_steps = profile["raman_steps"]
            quadrature_points = profile.get("xci_quadrature_points", XCI_EDGE_QUADRATURE_POINTS)
        if int(raman_iterations) < 1:
            raise ValueError(f"raman_iterations must be >= 1, got {raman_iterations}.")
        if not isinstance(raman_resolution_check, (bool, np.bool_)):
            raise ValueError(f"raman_resolution_check must be a bool, got {raman_resolution_check!r}.")
        resolved_resolution_tol = float(raman_resolution_tol)
        if not np.isfinite(resolved_resolution_tol) or resolved_resolution_tol <= 0.0:
            raise ValueError(
                f"raman_resolution_tol must be a finite positive fraction, got {raman_resolution_tol!r}."
            )
        if int(signal_polarizations) < 1:
            raise ValueError("signal_polarizations must be >= 1.")
        if not isinstance(pump_pump_raman, (bool, np.bool_)):
            raise ValueError(f"pump_pump_raman must be a bool, got {pump_pump_raman!r}.")
        resolved_guard = float(pump_signal_overlap_guard_hz)
        if not np.isfinite(resolved_guard):
            raise ValueError(
                f"pump_signal_overlap_guard_hz must be finite, got {pump_signal_overlap_guard_hz!r}."
            )
        resolved_convention = resolve_launch_power_convention(launch_power_convention, signal_polarizations)
        resolved_nli_convention = _resolve_nli_convention(nli_power_convention, resolved_convention)
        # 2019b 调制格式修正：Φ 必须是有限值，物理范围 [-2, 100]。负值是
        # 真实 QAM 的常态（16-QAM -0.680、64-QAM -0.619、256-QAM -0.605）；
        # -2 是超额峭度的理论下界，100 是防止明显非物理输入的工程上界。
        resolved_kurtosis = float(excess_kurtosis)
        if not np.isfinite(resolved_kurtosis) or resolved_kurtosis < -2.0 or resolved_kurtosis > 100.0:
            raise ValueError(
                "excess_kurtosis must be finite and within [-2, 100], "
                f"got {excess_kurtosis!r}."
            )
        mf_correction = bool(modulation_format_correction)
        if not mf_correction and resolved_kurtosis != 0.0:
            warnings.warn(
                "pcfm_h3_raman: excess_kurtosis is ignored unless "
                "modulation_format_correction=True. Pass modulation_format_correction=True to apply "
                "the Semrau 2019b correction.",
                UserWarning,
                stacklevel=2,
            )
        # 模型层没有单一跨长，这里只校验“位置为正、损耗非负、有限、排序合并”；
        # 位置上限留给每个 kernel 按各自光纤长度校验。
        self._lumped_loss, _, _ = _resolve_lumped_loss(lumped_loss, float("inf"))
        if resolved_convention == "total" and int(signal_polarizations) != 1:
            warnings.warn(
                "pcfm_h3_raman: launch_power_convention='total' with "
                f"signal_polarizations={int(signal_polarizations)} multiplies the Raman coupling drive "
                "by an undeclared unit factor. The input power is still the per-channel total power, "
                "so the signal photons are counted twice in the pump depletion and ISRS drive. Use "
                "launch_power_convention='per_pol' when power_in_w really is per-polarization power "
                "(the physical total is then 2x), or keep signal_polarizations=1.",
                UserWarning,
                stacklevel=2,
            )
        if span_coherence not in ("auto", "pcfm", "incoherent"):
            raise ValueError(
                f"span_coherence must be 'auto', 'pcfm' or 'incoherent', got {span_coherence!r}."
            )
        # EGN and span coherence must make the same decision for every span of
        # the link, so both resolve here from the same pump list.  A per-span
        # ``FiberSpanConfig.raman_pumps`` is only the fallback when neither the
        # model nor the reference fibre declares pumps.
        pump_source = raman_pumps or ref_fiber_config.raman_pumps
        resolved_egn = _resolve_egn(egn, pump_source)
        # 两套调制格式修正不能叠加：Zefreh 2020 的 rho 与 Semrau 2019b 的 Phi
        # 修的是同一个"高斯假设缺口"，同时开启会把同一个缺口修正两次。
        if mf_correction and resolved_kurtosis != 0.0 and resolved_egn:
            raise ValueError(
                "pcfm_h3_raman: modulation_format_correction=True cannot be combined with the "
                "Zefreh 2020 EGN correction (egn resolved to True); both correct the same "
                "Gaussian-assumption gap. Pass egn=False to use the Semrau 2019b correction, or "
                "leave modulation_format_correction=False to keep the EGN correction."
            )
        super().__init__(
            grid,
            ref_fiber_config,
            symbol_rate_hz=symbol_rate_hz,
            connections=connections,
            poly_degree=poly_degree,
            egn=resolved_egn,
            edge_fix=edge_fix,
            cache_spans=cache_spans,
            spp_steps=spp_steps,
            raman_model=None,
            raman_pumps=None,
            raman_gain_model=raman_gain_model,
            raman_gain_table=raman_gain_table,
            raman_ase=raman_ase,
            raman_temperature_k=raman_temperature_k,
            raman_peak_gain_coefficient_m_per_w=raman_peak_gain_coefficient_m_per_w,
            validity_mode=validity_mode,
            # 档位已在本类解析过（raman_steps 属于本类），不能再让父类重复解释。
            resolution=None,
            dense_grid_fix=dense_grid_fix,
            **route_options,
        )
        self._h3_raman_pumps = None if raman_pumps is None else list(raman_pumps)
        self._h3_raman_ase = bool(raman_ase)
        self._h3_raman_steps = raman_steps if isinstance(raman_steps, str) else int(raman_steps)
        self.resolution = None if profile is None else str(resolution)
        self.xci_edge_quadrature_points = int(quadrature_points)
        self._h3_raman_iterations = int(raman_iterations)
        self._h3_raman_resolution_check = bool(raman_resolution_check)
        self._h3_raman_resolution_tol = float(resolved_resolution_tol)
        self._h3_include_isrs = bool(include_isrs)
        self._h3_pump_depletion = bool(pump_depletion)
        self._signal_polarizations = int(signal_polarizations)
        self._h3_pump_pump_raman = bool(pump_pump_raman)
        self._launch_power_convention = resolved_convention
        self._nli_power_convention = resolved_nli_convention
        self._pump_signal_overlap_guard_hz = resolved_guard
        # 只有 Phi > 0 时才真正进入修正分支：Phi = 0 是恒等修正，必须逐位不变。
        self._modulation_format_correction = mf_correction
        self._excess_kurtosis = resolved_kurtosis
        self._mf_active = mf_correction and resolved_kurtosis != 0.0
        active_pumps = list(self._h3_raman_pumps or ref_fiber_config.raman_pumps or [])
        resolved = str(span_coherence)
        if resolved == "auto":
            resolved = "incoherent" if any(float(pump.power_w) > 0.0 for pump in active_pumps) else "pcfm"
        self.span_coherence = resolved
        # The route layer reads this attribute; an instance override selects the
        # power-sum convention without changing the PCFM class default.
        self.supports_span_context = self.span_coherence == "pcfm"

    @property
    def launch_power_convention(self) -> str:
        """Declared power convention of ``power_in_w`` (``"total"``/``"per_pol"``)."""
        return self._launch_power_convention

    @property
    def nli_power_convention(self) -> str:
        """Resolved power convention of the NLI kernels (``"total"``/``"per_pol"``)."""
        return self._nli_power_convention

    @nli_power_convention.setter
    def nli_power_convention(self, value: str) -> None:
        """Keep the parent ``PCFMModel.__init__`` assignment compatible."""
        self._nli_power_convention = value

    @property
    def pump_signal_overlap_guard_hz(self) -> float:
        """Guard added to each side of the signal band edges (Hz).

        ``0`` (default) keeps the literal channel-edge band and the round-Y
        point values; positive widens the band for the pump linewidth / WDM
        transition, negative shrinks it.  It only changes the validity report.
        """
        return float(self._pump_signal_overlap_guard_hz)

    @property
    def ase_polarization_scale(self) -> float:
        """Scale of newly generated EDFA/ROADM ASE for this model's coordinate.

        Only an end-to-end per-polarization model (launch *and* NLI both
        ``"per_pol"``) returns ``0.5``: its signal and NLI are per-polarization,
        so the dual-polarization ASE of the shared route layer must be halved
        once.  The Raman ASE is already produced in the same coordinate by
        :class:`~network_nlo_eval.models.raman_ode.RamanPaperSpanSolver`, so
        the route layer never scales ``input_ase_w``.  Any mixed convention
        keeps the historical total ASE (``1.0``).
        """
        if self._launch_power_convention == "per_pol" and self._nli_power_convention == "per_pol":
            return 0.5
        return 1.0

    @property
    def physical_power_scale(self) -> float:
        """Ratio between the physical total power and one ``power_in_w`` entry.

        The launch coordinate is what decides how much physical power one
        ``power_in_w`` entry carries, so this follows
        ``launch_power_convention`` and not the NLI convention.  That mirrors
        :meth:`PCFH3RamanSpanKernel._spp_drive_scale`: the ISRS profile is
        driven by the physical dual-polarization power even when the NLI
        kernels are already fed in the total coordinate.

        Returns
        -------
            ``2.0`` for a per-polarization launch, ``1.0`` otherwise.
        """
        return 2.0 if self._launch_power_convention == "per_pol" else 1.0

    @property
    def perf_ode_solves(self) -> int:
        """Coupled ODE solves actually performed by this model's kernels.

        The opt-in resolution audit increments it once per finer solve; with
        ``raman_resolution_check=False`` it only counts the solved-step result,
        so the default path is unchanged.
        """
        return sum(int(getattr(kernel, "perf_ode_solves", 0)) for kernel in self._kernel_cache.values())

    def _build_kernel(self, fiber_config: FiberSpanConfig) -> PCFH3RamanSpanKernel:
        """Build the profile-aware kernel of this fibre."""
        if self._h3_raman_pumps is not None:
            pumps = self._h3_raman_pumps
        else:
            pumps = fiber_config.raman_pumps or []
        active = [pump for pump in pumps if float(pump.power_w) > 0.0]
        if self._h3_raman_steps == "auto":
            steps = _resolve_auto_raman_steps(active, self.f_abs_hz)
        else:
            steps = int(self._h3_raman_steps)
        kernel = PCFH3RamanSpanKernel(
            self.f_abs_hz,
            self.channel_bandwidth_hz_channels,
            fiber_config,
            pumps=pumps,
            gain_model=self._raman_gain_model,
            raman_ase=self._h3_raman_ase,
            raman_steps=steps,
            raman_iterations=self._h3_raman_iterations,
            raman_resolution_check=self._h3_raman_resolution_check,
            raman_resolution_tol=self._h3_raman_resolution_tol,
            include_isrs=self._h3_include_isrs,
            pump_depletion=self._h3_pump_depletion,
            signal_polarizations=self._signal_polarizations,
            pump_pump_raman=self._h3_pump_pump_raman,
            launch_power_convention=self._launch_power_convention,
            nli_power_convention=self._nli_power_convention,
            pump_signal_overlap_guard_hz=self._pump_signal_overlap_guard_hz,
            lumped_loss=self._lumped_loss or None,
            poly_degree=self.poly_degree,
            symbol_rate_hz=self.symbol_rate_hz,
            egn=self.egn,
            edge_fix=self.edge_fix,
            cache_spans=self.cache_spans,
            spp_steps=self._active_spp_steps,
            xci_edge_quadrature_points=self.xci_edge_quadrature_points,
            dense_grid_fix=self.dense_grid_fix,
        )
        if self._mf_active:
            # 参考核与主核共用同一栅格/光纤/波长，因此 semrau2019 算出的
            # XPM 比值就是"同一功率剖面下"的 2019b 修正比例。
            kernel.attach_modulation_format_reference(
                Semrau2019SpanKernel(
                    fiber_config=fiber_config,
                    lambdas_m=self.lambdas_m,
                    f_rel_hz=self.f_rel_hz,
                    b_hz=self.channel_bandwidth_hz_channels,
                    band_center_hz=self.band_center_hz,
                    egn=True,
                    excess_kurtosis=self._excess_kurtosis,
                    srs_cr_w_m_hz=SRS_CR_W_M_HZ,
                )
            )
        return kernel

    def span_step(
        self,
        fiber_config: FiberSpanConfig,
        edfa_config,
        power_in_w: NDArrayFloat,
        span_length_m: float,
        span_context: SpanContext | None = None,
    ):
        """Evaluate one span without the lumped span-end gain block.

        The kernel already contains the Raman gain in the signal transfer and
        the Raman ASE in its output; applying the lumped amplifier on top would
        count the gain twice.  Everything after the fibre (EDFA, ROADM, ASE
        accumulation) is the shared route implementation.

        Args:
            fiber_config: Fibre parameters of the span.
            edfa_config: Amplifier configuration of the span.
            power_in_w: ``(N,)`` launch power per channel (W).
            span_length_m: Span length (m).
            span_context: Position of the span in the link.

        Returns
        -------
            The :class:`~network_nlo_eval.models.base.ElementOutput` of the span.
        """
        kernel = self.kernel_for(fiber_config)
        fiber_output = kernel.evaluate(
            power_in_w,
            span_length_m,
            1,
            span_index=(self._span_index if span_context is None else int(span_context.span_index)),
            beta2_accum_ps2=self._beta2_accum_ps2,
            span_context=span_context,
        )
        if self._mf_active:
            # 2019b 只修正 XPM/XCI：SCI 保持原值，XCI 乘参考核的逐信道比值。
            # 振幅按 sqrt(ratio) 缩放，保证 |amp|^2 仍等于 xpm_noise_w。
            n_spans = 1 if span_context is None else max(1, int(span_context.total_spans))
            ratio = kernel.modulation_format_ratio(power_in_w, span_length_m, n_spans)
            amplitude_xpm = fiber_output.nli_amplitude_xpm
            fiber_output = replace(
                fiber_output,
                xpm_noise_w=fiber_output.xpm_noise_w * ratio,
                nli_amplitude_xpm=None if amplitude_xpm is None else amplitude_xpm * np.sqrt(ratio),
            )
        self._record_span_validity(kernel, power_in_w, fiber_output.power_out_w, span_length_m)
        input_ase_w = kernel.last_raman_ase_w if (self._h3_raman_ase and kernel.active) else None
        nf_lin = resolve_noise_figure(edfa_config, self.default_nf_lin, self.n_nodes)
        element = apply_amplifier_and_roadm(
            power_in_w=power_in_w,
            fiber_output=fiber_output,
            edfa_config=edfa_config,
            roadm_config=None,
            nf_lin=nf_lin,
            f_abs_hz=self.f_abs_hz,
            bandwidth_hz=self.channel_bandwidth_hz_channels,
            input_ase_w=input_ase_w,
            ase_polarization_scale=self.ase_polarization_scale,
        )
        self._span_index += 1
        self._beta2_accum_ps2 = self._beta2_accum_ps2 + kernel.effective_dispersion_ps2(span_length_m)
        return element

    def evaluate_path_with_uncertainty(
        self,
        optical_path,
        power_in_w: NDArrayFloat,
        *,
        config: H3UncertaintyConfig | None = None,
    ) -> tuple[PathQoTResult, H3ErrorBudget]:
        """Evaluate a path and return the point result together with its budget.

        This is the opt-in proxy interface.  It calls :meth:`evaluate_path`
        unchanged and then builds the budget from the cached kernels, so the
        point result is bit-for-bit the default result and the default path
        never pays for the budget.

        Args:
            optical_path: Ordered path to evaluate.
            power_in_w: ``(N,)`` launch power (W).
            config: Optional budget configuration.

        Returns
        -------
            ``(result, budget)`` where ``result`` is the same
            :class:`~network_nlo_eval.models.base.PathQoTResult` that
            :meth:`evaluate_path` returns.
        """
        result = self.evaluate_path(optical_path, power_in_w)
        budget = estimate_h3_error_budget(self, optical_path, power_in_w, result, config=config)
        return result, budget


