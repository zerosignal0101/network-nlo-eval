"""Profile-aware fast PCFM for hybrid Raman links (``pcfm_h3_raman``).

The model keeps the H3 PCFM closed-form SCI/XCI kernels and adds the one thing
the lumped approximation cannot represent: the *normalised power profile*
``p_i(z) = P_i(z)/P_i(0)`` inside the span, as modified by the pump/signal
coupling.  The profile is fed to the same polynomial representation Eq. (23)
and the same island kernels Eq. (24)/(30) that the plain PCFM uses, so the NLI
responds to where the Raman gain is deposited instead of being multiplied by a
span-end gain.

**What is new relative to the lumped path**

``pcfm`` + ``raman_model="lumped"`` computes the passive (ISRS-only) profile,
then multiplies the span-end signal power by the on-off gain.  The NLI is
therefore independent of the pump.  This model solves the coupled signal/pump
power equations of Buglia et al. 2024 Eq. (2) (and the signal ASE Eq. (4)) on a
coarse RK4 grid, and uses the resulting profile in the PCFM kernels.  The
Raman ASE is the one generated by the same solve and is handed to the span
EDFA, exactly like ``hybrid_raman_paper``.

**Why this is an engineering approximation, not a second paper implementation**

* The coupled ODE is deliberately integrated with ``raman_steps`` (default 12)
  instead of the 32 steps of the full paper model.  The profile and the
  gain/ASE converge to the full solve within the model error budget; this is
  checked by the accuracy tests and the report.
* The solve is done with a zero input-ASE initial condition.  The accumulated
  ASE is transported by the shared route layer with the signal transfer factor,
  as in the lumped path.  The newly generated spontaneous Raman ASE does not
  depend on the input ASE, so the approximation is below the other error terms.
* The Raman gain spectrum is the repository Gaussian/CZ approximation, not the
  measured silica spectrum, and pump ASE / pump-signal XPM are not modelled.
  Those limitations are inherited from :mod:`network_nlo_eval.models.raman`.
* The *NLI formula* is the PCFM closed form, not Buglia Eq. (6)-(9).  The two
  kernels have a documented ~0.5 dB difference on a 10-span C-band link; this
  model reproduces the Raman-induced *change* (profile + ASE), not the absolute
  Buglia kernel baseline.  The difference is dominated by the inter-span
  convention: the paper uses ``n**epsilon`` with the unpublished ``epsilon=0``
  (power sum), while PCFM uses the visibility-weighted coherent sum.  The
  default here keeps the PCFM convention (it matches the numerical reference),
  and ``span_coherence="incoherent"`` is provided as an explicit paper-matched
  comparison mode.

**When there is no active pump the model is bit-for-bit the H3 PCFM**

The Raman branch is entered only when at least one pump has positive power.
With no pump the kernel delegates every operation to
:class:`~network_nlo_eval.models.pcfm.PCFMSpanKernel` and the route step passes
no Raman ASE, so the results are identical to ``pcfm`` with the same options.
"""

