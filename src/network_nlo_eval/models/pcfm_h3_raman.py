#: RK4 steps of the coarse Raman profile/ASE solve.
#:
#: The full paper model uses 32 steps.  At 12 steps the pump gain, the profile
#: shape and the Raman ASE of the C-band benchmark are within 0.05 dB of the
#: 32-step solve, while the cost is roughly halved.  The model is explicit
#: about this being a coarse solve: it is a fast profile provider, not a
#: replacement for the full paper ODE.
DEFAULT_H3_RAMAN_STEPS: int = 12

#: RK4 steps used by ``raman_steps="auto"`` when the comb reaches the S/E band
#: *and* the pump set is forward or multi-pump.
#:
#: The coupled ODE is stiff in this regime: the E+S+C+L six-pump comb at
#: 6 dBm/channel overflows at 24 steps (the backward fixed point never
#: converges, giving ``NaN``) and the forward six-pump solution is still
#: 0.3-1.9 dB off its 192-step value.  96 steps restores a finite, converged
#: solve; against 192 steps the per-channel residual is at most 0.027 dB
#: (backward) and 0.079 dB (forward), with a 0.01 dB mean.  C/C+L combs do not
#: reach the S band and keep their historical 12/24-step auto values, so their
#: numbers are bit-for-bit unchanged.
WIDEBAND_MULTIPUMP_RAMAN_STEPS: int = 96

#: Upper bound of the opt-in ``raman_resolution_check`` ladder.
#:
#: The check doubles the solved step count until it reaches this value.  The
#: cap keeps the extra work bounded (at most four extra solves per distinct
#: span) and matches the converged reference of the accuracy matrix
#: (``raman_steps=192`` is never exceeded in the calibration).
RAMAN_RESOLUTION_MAX_STEPS: int = 192

#: Relative tolerance of the opt-in ``raman_resolution_check``.
#:
#: The check compares the solved profile, span gain and newly generated Raman
#: ASE with a finer solve.  The value is calibrated on the round-12 matrix
#: (``H3_TASK_REPORT.md``):
#:
#: * C 57ch with one backward pump, 12 -> 192 steps: at most 4.9 % (0.20 dB
#:   gain), so 0.5 % would raise a false alarm on the validated 12-step C
#:   default;
#: * S+C+L 277ch / E+S+C+L 479ch six pumps, 96 -> 192 steps: 0.8 % / 1.4 %
#:   (0.03 / 0.06 dB), so 0.5 % would also flag the converged 96-step branch;
#: * C+L 152ch six pumps, 24 -> 48 steps: 18-22 % (0.7-0.9 dB), the AJ failure
#:   mode.
#:
#: ``0.10`` separates the AJ failure mode from both validated defaults with
#: margin.  It is a fraction of the profile/gain/ASE, not dB; a caller that
#: wants a stricter audit can pass ``raman_resolution_tol=0.005`` explicitly.
DEFAULT_RAMAN_RESOLUTION_TOL: float = 0.10

#: Upper edge of the C band (Hz), i.e. the lower edge of the S band.  A comb
#: with a channel centre above this value occupies S/E spectrum, where the
#: pumps of the six-pump set (1340-1505 nm) fall inside or next to the signal
#: band and the coupled ODE becomes stiff.  The 100 GHz guard above the
#: nominal 195.9 THz boundary keeps the C and C+L grids (whose highest centre
#: is exactly 195.9 THz) out of the extended-step rule.
C_BAND_UPPER_EDGE_HZ: float = 195.9e12
_WIDEBAND_EDGE_GUARD_HZ: float = 0.1e12

#: Default guard band added to each side of the occupied signal spectrum when
#: the pump/signal overlap is decided (Hz).
#:
#: The occupied band is ``[min(f_i - B_i/2), max(f_i + B_i/2)]`` over the
#: *launched* channels, extended by this guard.  ``0`` keeps the rule literal:
#: the pump linewidth is not modelled, so only a pump inside the channel band
#: edges (or within a deliberate positive guard) is flagged.  The value here is
#: only the default of the model/kernel option; a negative guard shrinks the
#: band and is allowed as an explicit control.
PUMP_SIGNAL_OVERLAP_GUARD_HZ: float = 0.0


def _occupied_signal_band(
    f_abs_hz: NDArrayFloat,
    bandwidths_hz: NDArrayFloat,
    active_channels: NDArrayBool,
    guard_hz: float,
) -> tuple[float, float] | None:
    """Return the guarded occupied signal band of the launched channels.

    The band is built from the channel *edges*, not the centres:
    ``[min(f_i - B_i/2) - guard, max(f_i + B_i/2) + guard]``.  Using edges makes
    the half-bandwidth of the outermost channels part of the occupied spectrum,
    so a pump between a centre and its edge is not missed.  A positive
    ``guard_hz`` widens the band (pump linewidth / WDM transition margin), a
    negative value shrinks it (explicit control).

    Args:
        f_abs_hz: ``(N,)`` channel centre frequencies (Hz), any order.
        bandwidths_hz: ``(N,)`` channel bandwidths ``B_i`` (Hz), same order.
        active_channels: ``(N,)`` boolean mask of launched channels.
        guard_hz: Guard added to each side (Hz), possibly negative.

    Returns
    -------
        ``(band_low_hz, band_high_hz)``, or ``None`` when there is no launched
        channel or the arrays do not share one shape.
    """
    centres = np.asarray(f_abs_hz, dtype=np.float64)
    bandwidths = np.asarray(bandwidths_hz, dtype=np.float64)
    mask = np.asarray(active_channels, dtype=bool)
    if (
        centres.size == 0
        or mask.shape != centres.shape
        or bandwidths.shape != centres.shape
        or not bool(np.any(mask))
    ):
        return None
    guard = float(guard_hz)
    half_bandwidth = 0.5 * bandwidths[mask]
    band_low = float(np.min(centres[mask] - half_bandwidth)) - guard
    band_high = float(np.max(centres[mask] + half_bandwidth)) + guard
    return band_low, band_high


def _pump_signal_overlap(
    pump_frequencies_hz: NDArrayFloat,
    f_abs_hz: NDArrayFloat,
    bandwidths_hz: NDArrayFloat,
    active_channels: NDArrayBool,
    guard_hz: float = PUMP_SIGNAL_OVERLAP_GUARD_HZ,
) -> tuple[bool, float]:
    """Return whether a pump lies inside the occupied signal band, and the offset.

    The band is ``[min(f_i - B_i/2), max(f_i + B_i/2)]`` over the launched
    channels, widened by ``guard_hz`` on both sides.  A pump inside that
    interval is a non-physical DRA configuration: it pumps the data band
    directly and cannot be separated from the signals by a WDM.  The distance
    is measured to the band *edge*, so it is ``0`` inside and positive outside;
    the minimum over the active pumps is the reported offset.

    Args:
        pump_frequencies_hz: ``(N_p,)`` active pump frequencies (Hz).
        f_abs_hz: ``(N,)`` channel centre frequencies (Hz), any order.
        bandwidths_hz: ``(N,)`` channel bandwidths ``B_i`` (Hz), same order.
        active_channels: ``(N,)`` boolean mask of launched channels.
        guard_hz: Guard added to each side of the channel edges (Hz).  ``0``
            (default) keeps the literal band; a negative value shrinks it.

    Returns
    -------
        ``(overlap, min_offset_hz)``.  Both are ``(False, inf)`` when there is
        no active pump or no launched channel.
    """
    pumps = np.asarray(pump_frequencies_hz, dtype=np.float64)
    band = _occupied_signal_band(f_abs_hz, bandwidths_hz, active_channels, guard_hz)
    if pumps.size == 0 or band is None:
        return False, float("inf")
    band_low, band_high = band
    # 到闭区间的距离：带内为 0，带外为正。取所有泵的最小值。
    offsets = np.where(
        pumps < band_low,
        band_low - pumps,
        np.where(pumps > band_high, pumps - band_high, 0.0),
    )
    min_offset = float(np.min(offsets))
    return bool(min_offset <= 0.0), min_offset


def _reaches_s_band(f_abs_hz: NDArrayFloat) -> bool:
    """Return whether any channel centre lies above the C band.

    The classification is deliberately based on the signal grid, not on a
    caller-supplied band string, so it also catches custom combs that extend
    into S/E.  The C and C+L benchmarks end exactly at 195.9 THz; the 0.1 THz
    guard keeps them on the historical auto path.

    Args:
        f_abs_hz: ``(N,)`` channel centre frequencies (Hz).

    Returns
    -------
        ``True`` when the comb reaches S/E spectrum.
    """
    if np.size(f_abs_hz) == 0:
        return False
    return bool(float(np.max(f_abs_hz)) > C_BAND_UPPER_EDGE_HZ + _WIDEBAND_EDGE_GUARD_HZ)


def _resolve_auto_raman_steps(
    active_pumps: Sequence[RamanPumpConfig],
    f_abs_hz: NDArrayFloat,
) -> int:
    """Pick ``raman_steps="auto"`` for one link.

    The rule is bounded and explicit:

    * no active pump, or one backward pump: 12 steps;
    * C/C+L with a forward or multi-pump set: 24 steps (historical);
    * S/E-containing comb with a forward or multi-pump set: 96 steps.

    A single backward pump never enters the extended branch, and C/C+L never
    changes value, so the historical defaults are preserved bit for bit.

    Args:
        active_pumps: Pumps with positive power.
        f_abs_hz: ``(N,)`` channel centre frequencies (Hz).

    Returns
    -------
        The RK4 step count of the coarse solve.
    """
    if not active_pumps:
        return DEFAULT_H3_RAMAN_STEPS
    hard_pump_set = any(str(pump.direction) == "forward" for pump in active_pumps) or len(active_pumps) >= 4
    if not hard_pump_set:
        return DEFAULT_H3_RAMAN_STEPS
    if _reaches_s_band(f_abs_hz):
        return WIDEBAND_MULTIPUMP_RAMAN_STEPS
    return 24


def _profile_sample_positions_u(result: PaperRamanSpanResult) -> NDArrayFloat:
    """Return the ``z/L`` position of every ``profile_norm`` row.

    The coarse solve samples the midpoint and the end of every RK4 step.  With
    lumped loss the steps are allocated per segment, so the positions are not
    uniform and the solver reports them explicitly; without loss they are the
    historical ``k/(2 n_steps)`` grid.

    Args:
        result: Result of one coupled solve.

    Returns
    -------
        ``(S,)`` normalised positions, strictly increasing.
    """
    if result.sample_positions_u is not None:
        return np.asarray(result.sample_positions_u, dtype=np.float64)
    n_rows = int(result.profile_norm.shape[0])
    return np.arange(1, n_rows + 1, dtype=np.float64) / n_rows


def _resample_profile_onto(
    profile: NDArrayFloat,
    source_positions_u: NDArrayFloat,
    target_positions_u: NDArrayFloat,
) -> NDArrayFloat:
    """Linearly interpolate a ``(S, N)`` profile onto other ``z/L`` positions.

    The finer check solve samples twice per coarse step, so the coarse
    positions are always inside the fine range (both end at ``z/L = 1``).
    Linear interpolation is enough: the quantity compared is a *relative*
    change of the smooth normalised signal profile, not a point value.

    Args:
        profile: ``(S, N)`` normalised profile of the finer solve.
        source_positions_u: ``(S,)`` positions of the finer rows.
        target_positions_u: ``(T,)`` positions to interpolate onto.

    Returns
    -------
        ``(T, N)`` resampled profile.
    """
    source = np.asarray(source_positions_u, dtype=np.float64)
    target = np.asarray(target_positions_u, dtype=np.float64)
    indices = np.searchsorted(source, target, side="right")
    indices = np.clip(indices, 1, source.size - 1)
    lower = indices - 1
    span = source[indices] - source[lower]
    weight = np.where(span > 0.0, (target - source[lower]) / span, 0.0)
    return profile[lower] * (1.0 - weight)[:, None] + profile[indices] * weight[:, None]


def _relative_vector_change(coarse: NDArrayFloat, fine: NDArrayFloat) -> float:
    """Largest relative change of two non-negative per-channel vectors.

    The denominator is floored at ``1e-12`` of the largest coarse value so a
    channel whose coarse entry is exactly zero (e.g. Raman ASE disabled) does
    not produce a division by zero.  Both vectors must already be restricted to
    the active channels.

    Args:
        coarse: ``(N,)`` solved-step result.
        fine: ``(N,)`` finer-step result.

    Returns
    -------
        The maximum relative change over the channels, or ``0`` when empty.
    """
    reference = np.asarray(coarse, dtype=np.float64)
    candidate = np.asarray(fine, dtype=np.float64)
    if reference.size == 0:
        return 0.0
    scale = float(np.max(np.abs(reference)))
    floor = max(scale * 1.0e-12, np.finfo(np.float64).tiny)
    return float(np.max(np.abs(candidate - reference) / np.maximum(np.abs(reference), floor)))


def _raman_resolution_change(
    coarse: PaperRamanSpanResult,
    fine: PaperRamanSpanResult,
    power_in_internal: NDArrayFloat,
    active: NDArrayBool,
) -> float:
    """Largest relative change between a coarse and a finer Raman solve.

    Three quantities are compared, all read from the same
    :class:`~network_nlo_eval.models.raman_ode.PaperRamanSpanResult` that drives
    the NLI profile:

    * the normalised signal profile, interpolated onto the coarse sample
      positions and divided by that channel's peak;
    * the span-end gain ``P_out / P_in``;
    * the newly generated Raman ASE.

    Comparing only the pump output would miss a signal-profile error that the
    pump solve hides, which is exactly the AJ failure mode.

    Args:
        coarse: Result at the solved step count.
        fine: Result at the finer step count.
        power_in_internal: ``(N,)`` launch power, internal channel order.
        active: ``(N,)`` boolean mask of launched channels (internal order).

    Returns
    -------
        The largest relative change over the active channels (fraction).
    """
    columns = np.flatnonzero(np.asarray(active, dtype=bool))
    if columns.size == 0:
        return 0.0
    coarse_profile = np.asarray(coarse.profile_norm, dtype=np.float64)[:, columns]
    fine_profile = np.asarray(fine.profile_norm, dtype=np.float64)[:, columns]
    coarse_positions = _profile_sample_positions_u(coarse)
    fine_positions = _profile_sample_positions_u(fine)
    if np.array_equal(coarse_positions, fine_positions):
        resampled = fine_profile
    else:
        resampled = _resample_profile_onto(fine_profile, fine_positions, coarse_positions)
    peaks = np.max(np.abs(coarse_profile), axis=0)
    usable = peaks > 0.0
    if np.any(usable):
        profile_change = float(
            np.max(np.max(np.abs(resampled[:, usable] - coarse_profile[:, usable]), axis=0) / peaks[usable])
        )
    else:
        profile_change = 0.0

    power = np.asarray(power_in_internal, dtype=np.float64)[columns]
    coarse_gain = np.asarray(coarse.power_out_w, dtype=np.float64)[columns] / power
    fine_gain = np.asarray(fine.power_out_w, dtype=np.float64)[columns] / power
    gain_change = _relative_vector_change(coarse_gain, fine_gain)
    ase_change = _relative_vector_change(
        np.asarray(coarse.raman_ase_w, dtype=np.float64)[columns],
        np.asarray(fine.raman_ase_w, dtype=np.float64)[columns],
    )
    return max(profile_change, gain_change, ase_change)


