r"""Capture the FG-4a numeric golden: every scenario's full-precision output.

This is an **evidence generator**, not a test. It freezes the FG-4a acceleration
gate by recording, for each fixed scenario in :mod:`tests.fg4a_scenarios`, the
complete ``repr``-precision values of the quantities the model must keep
producing: ``p_out`` / ``spm`` / ``xpm`` / ``ase`` per span, and
``signal_power`` / ``spm`` / ``xpm`` / ``ase`` / ``snr`` for a full path.

Design notes
------------
* **Precision.** Arrays are stored as nested JSON lists of Python floats.
  ``json`` writes floats with ``float.__repr__`` — the shortest string that
  round-trips to the same IEEE-754 double — so ``json.load`` restores the exact
  bit pattern. Nothing is rounded; the golden is not a printout.

* **Where it is captured.** Scenarios are driven through the *stable evaluator
  API* (``_calc_span_noise_and_power`` / ``evaluate_path``), never through the
  njit kernel's argument list. That is deliberate: FG-4a changes the kernel's
  internals and signature, and a kernel-level golden would have to be
  regenerated by those very changes, which would make the gate circular.

* **When it is captured.** Before any FG-4a acceleration, i.e. at the baseline
  commit ``ea7ecb0``.

Regenerate (only ever at the baseline, never after an optimisation)::

    PYTHONPATH=$PWD/src NUMBA_CACHE_DIR=/tmp/fg-fast-nb \\
        $HOME/miniconda3/envs/rl/bin/python scripts/fg4a_capture_golden.py \\
        --out results/fg4a_golden.json

``--check`` re-runs the scenarios and reports whether the current code still
reproduces the stored golden bit-for-bit, without overwriting it.
"""

from __future__ import annotations

import argparse
import json
import platform
import subprocess
import sys
from pathlib import Path
from typing import Any

import numpy as np

REPO_ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO_ROOT / "tests"))

from fg4a_scenarios import PATH_KEYS, SPAN_KEYS, build_scenarios  # noqa: E402

DEFAULT_OUT = REPO_ROOT / "results" / "fg4a_golden.json"


def _git_rev() -> str:
    """Record the commit the golden was produced at."""
    try:
        return subprocess.run(
            ["git", "rev-parse", "HEAD"], cwd=REPO_ROOT, capture_output=True, text=True, check=True
        ).stdout.strip()
    except (OSError, subprocess.CalledProcessError):  # pragma: no cover
        return "unknown"


def _package_path() -> str:
    """Record which ``network_nlo_eval`` tree actually served the numbers.

    The repo is installed editable with a ``.pth`` pointing at the *main*
    checkout, which is independent of the cwd. Writing the resolved path into
    the golden makes a mis-scoped ``PYTHONPATH`` immediately visible instead of
    silently turning the gate green against another tree's code.
    """
    import network_nlo_eval

    return str(Path(network_nlo_eval.__file__).resolve())


#: The golden must always be produced on a path that is bit-identical to the
#: baseline. ``cached_g`` is used because it is proven bit-identical to the
#: frozen reference (``off``) by ``test_f4a_3_cached_g_matches_off_exactly``, so
#: the golden stays reproducible from the current tree — which would not be true
#: if it were written through ``matvec``.
CAPTURE_MODE = "cached_g"


def collect(ode_accel: str = CAPTURE_MODE, *, for_capture: bool = False) -> dict[str, Any]:
    """Run every scenario and return the full golden payload.

    Args:
        ode_accel: Acceleration mode for the evaluators. Must be a **bit-exact**
            mode (see :data:`CAPTURE_MODE`); ``matvec`` is not permitted for
            capture, because writing the golden through a path that is allowed
            to differ would bake the rounding shift into the reference.
    """
    if ode_accel == "matvec" and for_capture:
        raise ValueError(
            "the golden must not be captured through the 'matvec' mode; it is allowed to "
            "differ from the baseline. Pass 'off' or 'cached_g'."
        )
    scenarios = build_scenarios(ode_accel)
    effective = ode_accel
    payload: dict[str, Any] = {
        "schema_version": 1,
        "description": (
            "FG-4a numeric golden: full-precision QoT outputs per fixed scenario. "
            "JSON floats are repr-encoded, so load restores the exact IEEE-754 bits. "
            "Compare with np.array_equal (tests/test_fg4a_numeric_identity.py)."
        ),
        "provenance": {
            "git_rev": _git_rev(),
            "package_path": _package_path(),
            "python": platform.python_version(),
            "numpy": np.__version__,
            "captured_at_stage": "pre-FG-4a baseline",
            "ode_accel": effective,
        },
        "scenarios": {},
    }
    for scenario in scenarios:
        expected = SPAN_KEYS if scenario.kind == "span" else PATH_KEYS
        outputs = scenario.outputs()
        missing = [key for key in expected if key not in outputs]
        if missing:
            raise RuntimeError(f"scenario {scenario.name!r} is missing outputs: {missing}")
        payload["scenarios"][scenario.name] = {
            "kind": scenario.kind,
            "description": scenario.description,
            "outputs": outputs,
        }
    return payload


def _compare(expected: dict[str, Any], actual: dict[str, Any], tolerance: float) -> tuple[list[str], dict[str, Any]]:
    """Compare two golden payloads; return (problems, statistics).

    ``np.array_equal`` with ``equal_nan=True`` decides bit-exactness, so matching
    infinities count as equal — ``snr_db`` legitimately contains ``+/-inf`` for
    blocked or noiseless channels. Deviation statistics are taken over the
    elements finite on both sides only; a change in *which* entries are infinite
    is reported as a hard failure, because that is a semantic change rather than
    a float-reordering one.
    """
    problems: list[str] = []
    stats = {
        "cases": 0,
        "bit_exact_cases": 0,
        "differing_elements": 0,
        "max_rel_deviation": 0.0,
        "max_rel_deviation_at": "-",
    }
    exp_scenarios = expected.get("scenarios", {})
    act_scenarios = actual.get("scenarios", {})
    if set(exp_scenarios) != set(act_scenarios):
        problems.append(f"scenario set differs: golden={sorted(exp_scenarios)} current={sorted(act_scenarios)}")
    for name in sorted(set(exp_scenarios) & set(act_scenarios)):
        exp_out = exp_scenarios[name]["outputs"]
        act_out = act_scenarios[name]["outputs"]
        for key in sorted(set(exp_out) | set(act_out)):
            if key not in exp_out or key not in act_out:
                problems.append(f"{name}.{key}: present in only one of the two")
                continue
            exp_arr = np.asarray(exp_out[key], dtype=np.float64)
            act_arr = np.asarray(act_out[key], dtype=np.float64)
            if exp_arr.shape != act_arr.shape:
                problems.append(f"{name}.{key}: shape {exp_arr.shape} != {act_arr.shape}")
                continue

            stats["cases"] += 1
            if exp_arr.size == 0:
                stats["bit_exact_cases"] += 1
                continue

            nonfinite_mismatch = int(np.count_nonzero(np.isfinite(exp_arr) != np.isfinite(act_arr)))
            if nonfinite_mismatch:
                problems.append(
                    f"{name}.{key}: {nonfinite_mismatch} elements changed between finite and "
                    "infinite — a semantic change, not a rounding shift"
                )

            both_finite = np.isfinite(exp_arr) & np.isfinite(act_arr)
            if np.array_equal(exp_arr, act_arr, equal_nan=True):
                stats["bit_exact_cases"] += 1
                continue

            differing = int(np.count_nonzero(exp_arr != act_arr))
            stats["differing_elements"] += differing
            if both_finite.any():
                exp_f = exp_arr[both_finite]
                act_f = act_arr[both_finite]
                diff = np.abs(exp_f - act_f)
                denom = np.abs(exp_f)
                # ``np.divide(..., where=)`` instead of ``np.where(denom>0, a/b, 0)``:
                # the latter still evaluates a/b for masked-out elements and emits
                # an invalid-value warning for 0/0.
                rel = np.divide(diff, denom, out=np.zeros_like(diff), where=denom > 0)
                max_rel = float(rel.max())
                if max_rel > stats["max_rel_deviation"]:
                    stats["max_rel_deviation"] = max_rel
                    stats["max_rel_deviation_at"] = f"{name}.{key}"
                if max_rel > tolerance:
                    problems.append(
                        f"{name}.{key}: relative deviation {max_rel:.3e} exceeds {tolerance:.0e} "
                        f"(max abs {float(diff.max()):.3e}, {differing}/{exp_arr.size} differ)"
                    )
    return problems, stats


def main() -> int:
    """Generate or check the golden file."""
    from network_nlo_eval.models.isrs_gn import ODE_ACCEL_DEFAULT, ODE_ACCEL_MODES

    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out", type=Path, default=DEFAULT_OUT, help="golden JSON path")
    parser.add_argument(
        "--check",
        action="store_true",
        help="compare against the stored golden instead of overwriting it",
    )
    parser.add_argument(
        "--ode-accel",
        default=ODE_ACCEL_DEFAULT,
        choices=list(ODE_ACCEL_MODES),
        help="acceleration mode to run while checking (default: %(default)s)",
    )
    parser.add_argument(
        "--tolerance",
        type=float,
        default=1e-12,
        help="relative deviation allowed in --check mode (default: %(default)s)",
    )
    args = parser.parse_args()

    if args.check:
        actual = collect(args.ode_accel)
        if not args.out.exists():
            print(f"golden {args.out} does not exist", file=sys.stderr)
            return 2
        expected = json.loads(args.out.read_text(encoding="utf-8"))
        problems, stats = _compare(expected, actual, args.tolerance)
        print(
            f"checked with ode_accel={args.ode_accel!r}, tolerance={args.tolerance:.0e}: "
            f"{stats['bit_exact_cases']}/{stats['cases']} cases bit-identical, "
            f"worst relative deviation {stats['max_rel_deviation']:.3e} "
            f"at {stats['max_rel_deviation_at']} "
            f"({stats['differing_elements']} differing elements in total)"
        )
        if problems:
            print(f"FAIL: {len(problems)} problem(s) against {args.out}")
            for line in problems:
                print(f"  - {line}")
            return 1
        print(f"OK: current code reproduces {args.out} within tolerance")
        return 0

    # Writing always goes through the bit-exact capture mode.
    actual = collect(CAPTURE_MODE, for_capture=True)
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(json.dumps(actual, indent=2, sort_keys=True) + "\n", encoding="utf-8")

    print(f"wrote {args.out}")
    print(f"git rev      : {actual['provenance']['git_rev']}")
    print(f"package      : {actual['provenance']['package_path']}")
    print(f"numpy/python : {actual['provenance']['numpy']} / {actual['provenance']['python']}")
    for name, entry in actual["scenarios"].items():
        shapes = {key: np.shape(value) for key, value in entry["outputs"].items()}
        print(f"  {name:22s} {entry['kind']:4s} {shapes}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
